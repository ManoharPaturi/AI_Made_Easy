def fit_encoders(frame) -> None:
    missing = [c for c in [*COLUMNS, *GROUPS] if c not in frame.columns]
    if missing:
        raise SystemExit(f"the data has no column(s) {missing}; columns: {list(frame.columns)}")
    STATE["levels"] = {g: sorted(frame[g].astype(str).unique().tolist()) for g in GROUPS}
    STATE["categories"] = {c: sorted(frame[c].astype(str).unique().tolist())
                           for c in CATEGORICAL}


def to_model_data(frame, observed_values: bool = True) -> dict:
    """Arrays for build_model: data columns, group codes and observed values."""
    data = {"_rows": np.arange(len(frame))}
    for col in COLUMNS:
        if col in CATEGORICAL:
            codes = {c: i for i, c in enumerate(STATE["categories"][col])}
            data[col] = frame[col].astype(str).map(codes).fillna(0).to_numpy().astype(int) \
                if col in frame else np.zeros(len(frame), int)
            continue
        kind = next((k for c, k in OBSERVED.values() if c == col), "real")
        is_observed = col in [c for c, _k in OBSERVED.values()]
        if col not in frame or (is_observed and not observed_values):
            values = np.zeros(len(frame))
        else:
            values = pd.to_numeric(frame[col], errors="coerce").to_numpy(float)
            if np.isnan(values).any():
                raise SystemExit(f"column {col!r} has missing or non-numeric values")
        data[col] = values.astype(int) if kind in ("count", "binary") else values
    for g in GROUPS:
        index = {lvl: i for i, lvl in enumerate(STATE["levels"][g])}
        codes = frame[g].astype(str).map(index)
        if codes.isna().any():
            unknown = sorted(set(frame[g].astype(str)) - set(index))[:5]
            raise ValueError(f"unknown {g} level(s) {unknown}: the model has "
                             f"{STATE['levels'][g][:10]}")
        data[g + "__code"] = codes.to_numpy(int)
    return data



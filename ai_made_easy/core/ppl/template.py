def _dataset(graph: Graph) -> dict | None:
    from ai_made_easy.core.ppl.tasks import dataset_of

    node = dataset_of(graph)
    if node is None:
        return None
    out = {"block": node.type_id, **dict(node.resolved_params())}
    raw = out.get("path")
    if raw and not str(raw).startswith("~") and not Path(str(raw)).is_absolute():
        candidate = Path.cwd() / str(raw)
        if candidate.exists():
            out["path"] = str(candidate)
    return out


def render(graph: Graph) -> str:
    from ai_made_easy.core.ppl.rules import ppl_issues

    errors = [i for i in ppl_issues(graph) if i.severity == "error"]
    if errors:
        raise CodegenError("the probabilistic program has errors:\n"
                           + "\n".join(f"  - {e.message}" for e in errors))
    try:
        compiled = compile_design(graph)
    except ModelError as exc:
        raise CodegenError(str(exc)) from None
    vars_, info = compiled["vars"], compiled["info"]
    sampler = next((dict(n.resolved_params()) for n in graph.nodes.values()
                    if n.type_id == "ppl.sampler"), dict(DEFAULT_SAMPLER))
    notes = []
    if not info["observed"]:
        notes.append("no variable is observed: this samples the prior only")
    observed = {v.name: (v.observed, BY_ID[v.type_id].support) for v in vars_ if v.observed}
    model_lines = model_code(vars_, info)
    coord_expr = "{" + ", ".join(f"{identifier(g)!r}: STATE['levels'][{g!r}]"
                                 for g in info["groups"]) + "}"
    name = sanitize_identifier(graph.name)
    dataset = _dataset(graph)
    return _env.from_string(TEMPLATE).render(
        title=graph.name, filename=f"{name}_train_pymc.py", name=name, notes=notes,
        data_comment=_comment(dataset), dataset=dataset, sampler=sampler,
        columns=info["columns"], groups=info["groups"], observed=observed,
        categorical=compiled["categorical"], coord_expr=coord_expr, model_lines=model_lines,
        data_code=runtime.DATA_CODE, diagnostics_code=runtime.DIAGNOSTICS_CODE,
        plot_code=runtime.PLOT_CODE)


def _comment(dataset: dict | None) -> str:
    if dataset is None:
        return "none"
    if dataset["block"] == "data.synthetic_groups":
        return (f"generated: {dataset['n_groups']} groups, about {dataset['rows_per_group']} "
                f"rows each ({dataset['outcome']} outcome)")
    return str(dataset.get("path"))

def free_names(model) -> list[str]:
    return [rv.name for rv in model.free_RVs]


def sample(model) -> dict:
    """Posterior draws: name -> [chains, draws, ...]; plus sampler statistics."""
    cfg = SAMPLER
    stats: dict = {"divergences": 0}
    with model:
        if cfg["method"] == "map":
            point = pm.find_MAP(progressbar=False, seed=cfg["seed"])
            return {n: np.asarray(point[n])[None, None] for n in free_names(model)}, stats
        if cfg["method"] == "advi":
            approx = pm.fit(n=cfg["advi_iterations"], method="advi", random_seed=cfg["seed"],
                            progressbar=False)
            trace = approx.sample(cfg["draws"], random_seed=cfg["seed"])
        elif cfg["method"] == "smc":
            trace = pm.sample_smc(cfg["draws"], chains=cfg["chains"], random_seed=cfg["seed"],
                                  progressbar=False)
        else:
            kwargs = {"nuts_sampler": "numpyro"} if cfg["backend"] == "numpyro" else {}
            trace = pm.sample(cfg["draws"], tune=cfg["tune"], chains=cfg["chains"],
                              target_accept=cfg["target_accept"], random_seed=cfg["seed"],
                              progressbar=False, compute_convergence_checks=False, **kwargs)
            stats["divergences"] = int(np.asarray(trace["sample_stats"]["diverging"]).sum())
    posterior = trace["posterior"]
    return {n: np.asarray(posterior[n]) for n in free_names(model)}, stats


def points(draws: dict, limit: int = 400) -> list[dict]:
    """Up to ``limit`` posterior points (a single MAP point is repeated so that predictions
    still include the likelihood's noise)."""
    chains, n = next(iter(draws.values())).shape[:2]
    flat = {k: v.reshape(chains * n, *v.shape[2:]) for k, v in draws.items()}
    total = chains * n
    idx = np.linspace(0, total - 1, min(limit, total)).astype(int) if total > 1 else \
        np.zeros(limit, int)
    return [{k: v[i] for k, v in flat.items()} for i in idx]


def predict(frame, draws: dict, observed_values: bool = True) -> dict:
    """Posterior predictive draws of every observed variable for these rows."""
    data = to_model_data(frame, observed_values)
    model = build_model(data)
    with model:
        pp = pm.sample_posterior_predictive(points(draws), var_names=list(OBSERVED),
                                            random_seed=SAMPLER["seed"], progressbar=False)
    group = pp["posterior_predictive"]
    return {n: np.asarray(group[n]).reshape(-1, len(frame)) for n in OBSERVED}


def check(frame, preds: dict, prefix: str) -> dict:
    out = {}
    for name, (column, kind) in OBSERVED.items():
        sims = preds[name]
        actual = frame[column]
        if column in CATEGORICAL:
            codes = {c: i for i, c in enumerate(STATE["categories"][column])}
            actual = actual.astype(str).map(codes).to_numpy()
            mode = np.array([np.bincount(s.astype(int)).argmax() for s in sims.T])
            out[f"{prefix}_{name}_accuracy"] = float(np.mean(mode == actual))
            continue
        actual = pd.to_numeric(actual).to_numpy(float)
        lo, hi = np.quantile(sims, [0.03, 0.97], axis=0)
        mean = sims.mean(0)
        out[f"{prefix}_{name}_coverage_94"] = float(np.mean((actual >= lo) & (actual <= hi)))
        if kind == "binary":
            out[f"{prefix}_{name}_accuracy"] = float(np.mean((mean > 0.5) == (actual > 0.5)))
        else:
            out[f"{prefix}_{name}_rmse"] = float(np.sqrt(np.mean((mean - actual) ** 2)))
        if prefix == "train":
            SAMPLES_DIR.mkdir(exist_ok=True)
            ppc_plot(actual, mean, lo, hi, f"{name}: observed vs posterior predictive").save(
                SAMPLES_DIR / f"ppc_{name}.png")
    return out



def fix_pytensor_macos() -> None:
    """Recent Xcode linkers reject PyTensor's '-ld64' flag on macOS: drop it."""
    if sys.platform != "darwin":
        return
    try:
        from pytensor.link.c import cmodule
    except ImportError:
        return
    original = cmodule.GCC_compiler.compile_args
    if getattr(original, "_aime_patched", False):
        return

    def compile_args(*args, **kwargs):
        return [a for a in original(*args, **kwargs) if a != "-ld64"]

    compile_args._aime_patched = True
    cmodule.GCC_compiler.compile_args = staticmethod(compile_args)



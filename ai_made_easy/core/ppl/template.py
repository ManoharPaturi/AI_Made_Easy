def infer(raw: list) -> list[dict]:
    """Rows of input columns (and group levels) -> the posterior predictive of each
    observed variable: mean, sd and a 94% interval (probabilities for yes / no)."""
    if _PREDICTOR is None:
        raise RuntimeError("call load_predictor(folder) first")
    frame = pd.DataFrame([dict(r) for r in raw])
    preds = predict(frame, _PREDICTOR, observed_values=False)
    out = []
    for i in range(len(frame)):
        row = {}
        for name, (column, kind) in OBSERVED.items():
            sims = preds[name][:, i]
            if column in CATEGORICAL:
                counts = np.bincount(sims.astype(int), minlength=len(STATE["categories"][column]))
                row[name] = {c: round(float(p), 4) for c, p in
                             zip(STATE["categories"][column], counts / counts.sum())}
            elif kind == "binary":
                row[name] = {"probability": round(float(sims.mean()), 4)}
            else:
                lo, hi = np.quantile(sims, [0.03, 0.97])
                row[name] = {"mean": round(float(sims.mean()), 4),
                             "sd": round(float(sims.std()), 4),
                             "lower_94": round(float(lo), 4), "upper_94": round(float(hi), 4)}
        out.append(row)
    return out



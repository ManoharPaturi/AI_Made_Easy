def _strip_main(code: str) -> str:
    head, _sep, _tail = code.partition('\n\nif __name__ == "__main__":')
    body = head.split('\nfrom __future__ import annotations\n', 1)[-1]
    lines = [ln for ln in body.splitlines()
             if not ln.startswith(("import torch", "import torch.nn as nn",
                                   "import torch.nn.functional as F"))]
    return "\n".join(lines).strip("\n") + "\n"


def _picked(graph: Graph, ids) -> tuple:
    found = [n for n in graph.nodes.values() if n.type_id in ids]
    return (found[0], dict(found[0].resolved_params())) if found else (None, {})


def _dataset(graph: Graph) -> dict:
    node = dataset_of(graph)
    if node is None:
        return {"block": "data.synthetic_series", "n_series": 30, "length": 400, "trend": 0.2,
                "noise": 0.1, "counts": False, "promotions": False, "seed": 0, "window": 48,
                "horizon": 12, "stride": 1, "season_length": 24, "val_windows": 2,
                "test_windows": 2}
    out = {"block": node.type_id, **dict(node.resolved_params())}
    raw = out.get("path")
    if raw and not str(raw).startswith("~") and not Path(str(raw)).is_absolute():
        candidate = Path.cwd() / str(raw)
        if candidate.exists():
            out["path"] = str(candidate)
    return out


def context(graph: Graph, framework: str) -> dict:
    if framework != "pytorch":
        raise CodegenError("forecasting trains with PyTorch: choose the PyTorch framework")
    notes: list[str] = []
    dataset = _dataset(graph)
    if dataset_of(graph) is None:
        notes.append("no dataset block: training on generated seasonal series")
    model = model_of(graph)
    params = dict(model.resolved_params()) if model is not None else {"head": "point"}
    chain = graph.model_nodes()
    shapes = graph.infer_shapes()
    input_shape = list(shapes[chain[0].instance_id])
    _t, trainer = _picked(graph, ("train.trainer",))
    trainer = cat.resolved("train.trainer", trainer)
    _l, loader = _picked(graph, ("prep.dataloader",))
    loss_node, _lp = _picked(graph, tuple(POINT_LOSSES))
    head = params.get("head", "point")
    if head != "point" and loss_node is not None:
        notes.append(f"{loss_node.definition().display_name} is ignored: the {head} head "
                     "trains with its own loss")
    opt, opt_params = _picked(graph, cat.OPTIMIZER_IDS)
    optimizer = ("torch.optim.Adam(params, lr=0.001)" if opt is None else
                 cat.render(opt.type_id, cat.resolved(opt.type_id, opt_params), "pytorch")
                 .replace("model.parameters()", "params"))
    sched, sched_params = _picked(graph, cat.SCHEDULER_IDS)
    name = sanitize_identifier(graph.name)
    model_code = generate(graph, "pytorch")
    from ai_made_easy.core.training.generate import own_loop_requirements

    return {
        "requirements": own_loop_requirements(
            model_code, ("pandas",) if dataset["block"] == "data.forecast_csv" else ()),
        "title": graph.name, "filename": f"{name}_train_pytorch.py", "name": name,
        "notes": notes, "data_comment": _data_comment(dataset),
        "model_label": model.definition().display_name if model else "custom layers",
        "dataset": dataset, "window": int(dataset["window"]),
        "horizon": int(dataset["horizon"]), "stride": int(dataset["stride"]),
        "season": int(dataset["season_length"]), "val_windows": int(dataset["val_windows"]),
        "test_windows": int(dataset["test_windows"]),
        "head": head, "quantiles": list(quantile_levels(params)) or [0.5],
        "point_loss": POINT_LOSSES.get(loss_node.type_id, "mse") if loss_node else "mse",
        "input_shape": input_shape, "trainer": trainer,
        "batch_size": int(loader.get("batch_size") or 0) or int(trainer["batch_size"]),
        "model_code": _strip_main(model_code),
        "data_code": runtime.DATA_CODE, "metrics_code": runtime.METRICS_CODE,
        "plot_code": runtime.PLOT_CODE, "optimizer_expr": optimizer,
        "scheduler_expr": (cat.render(sched.type_id, cat.resolved(sched.type_id, sched_params),
                                      "pytorch") if sched else None),
        "scheduler_step": cat.COMPONENTS[sched.type_id].meta["step"] if sched else None,
    }


def _data_comment(dataset: dict) -> str:
    if dataset["block"] == "data.synthetic_series":
        return (f"{dataset['n_series']} generated series of {dataset['length']} steps "
                f"(season {dataset['season_length']})")
    return f"{dataset['path']} (target '{dataset['target_column']}')"


def render(graph: Graph, _spec, framework: str) -> str:
    return _env.from_string(TEMPLATE).render(**context(graph, framework))


def register() -> None:
    from ai_made_easy.core.training.generate import register_trainer

    register_trainer("forecasting", render, needs_spec=False)

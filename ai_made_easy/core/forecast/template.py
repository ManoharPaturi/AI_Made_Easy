_PREDICTOR = None


def load_predictor(folder: str | Path = ".", device: str = "cpu") -> nn.Module:
    global _PREDICTOR
    with open(Path(folder) / INFERENCE_FILE, "rb") as fh:
        STATE.update(pickle.load(fh))
    model = build_model()
    model.load_state_dict(torch.load(Path(folder) / CHECKPOINT, map_location=device))
    _PREDICTOR = model.eval().to(device)
    return _PREDICTOR


@torch.no_grad()
def infer(raw: list) -> list[dict]:
    """Forecasts for series histories: a list of numbers, or a dict with "history",
    "past_covariates" ([T][P]) and "future_covariates" ([T + horizon][F]) rows."""
    if _PREDICTOR is None:
        raise RuntimeError("call load_predictor(folder) first")
    device = next(_PREDICTOR.parameters()).device
    results = []
    for item in raw:
        item = item if isinstance(item, dict) else {"history": item}
        history = np.asarray(item["history"], np.float32)
        if len(history) < WINDOW:
            raise ValueError(f"history needs at least {WINDOW} values, got {len(history)}")
        n_future = int(STATE.get("n_future", 0))
        n_past = len(STATE["cov_mean"]) - n_future
        # covariates the request leaves out are filled with zeros (their "absent" value)
        past = np.asarray(item.get("past_covariates") or np.zeros((len(history), n_past)),
                          np.float32).reshape(len(history), -1)
        fut_all = np.asarray(item.get("future_covariates") or
                             np.zeros((len(history) + HORIZON, n_future)), np.float32)
        fut_all = fut_all.reshape(len(fut_all), -1)
        if past.shape[1] != n_past or fut_all.shape[1] != n_future:
            raise ValueError(f"the model was trained with {n_past} past and {n_future} future "
                             f"covariate(s); got {past.shape[1]} and {fut_all.shape[1]}")
        if len(fut_all) < len(history) + HORIZON:
            raise ValueError(f"future_covariates needs {len(history) + HORIZON} rows (history "
                             f"+ horizon), got {len(fut_all)}")
        x = np.concatenate([history[:, None], past, fut_all[: len(history)]], axis=1)[-WINDOW:]
        future = fut_all[len(history): len(history) + HORIZON].reshape(HORIZON, -1)
        xs, fs, scale = prepare(x[None], future[None])
        out = run_model(_PREDICTOR, torch.from_numpy(xs).to(device),
                        torch.from_numpy(fs).to(device))
        desc = describe(out, torch.from_numpy(scale).to(device))
        result = {"forecast": desc["point"][0].cpu().numpy().astype(float).round(4).tolist()}
        for key in ("lower", "upper"):
            if key in desc:
                result[key] = desc[key][0].cpu().numpy().astype(float).round(4).tolist()
        if "quantiles" in desc:
            q = desc["quantiles"][0].cpu().numpy().astype(float)
            result["quantiles"] = {str(lv): q[:, j].round(4).tolist()
                                   for j, lv in enumerate(QUANTILES)}
        results.append(result)
    return results



@torch.no_grad()
def vae_validate(model, val_x, device) -> dict:
    model.eval()
    totals, n = np.zeros(2), 0
    for start in range(0, len(val_x), 256):
        x = val_x[start:start + 256].to(device)
        recon, kl, _ = vae_losses(model, x)
        totals += np.array([recon.item(), kl.item()]) * len(x)
        n += len(x)
    return {"recon": totals[0] / n, "kl": totals[1] / n, "elbo": totals.sum() / n}


# ======================================================================== GAN
def d_loss(disc, real, fake) -> torch.Tensor:
    real_score, fake_score = disc(real), disc(fake)
    if GAN["loss"] == "hinge":
        return nn.functional.relu(1 - real_score).mean() + nn.functional.relu(1 + fake_score).mean()
    if GAN["loss"] == "wgan_gp":
        eps = torch.rand(real.shape[0], 1, 1, 1, device=real.device)
        mixed = (eps * real + (1 - eps) * fake).requires_grad_(True)
        grad = torch.autograd.grad(disc(mixed).sum(), mixed, create_graph=True)[0]
        penalty = ((grad.flatten(1).norm(dim=1) - 1) ** 2).mean()
        return fake_score.mean() - real_score.mean() + GAN["gp_weight"] * penalty
    return nn.functional.softplus(-real_score).mean() + nn.functional.softplus(fake_score).mean()


def g_loss(disc, fake) -> torch.Tensor:
    score = disc(fake)
    return nn.functional.softplus(-score).mean() if GAN["loss"] == "bce" else -score.mean()



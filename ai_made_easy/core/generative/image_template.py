# ======================================================================== shared
def pick_device() -> torch.device:
    if DEVICE != "auto":
        return torch.device(DEVICE)
    if torch.cuda.is_available():
        return torch.device("cuda")
    if torch.backends.mps.is_available():
        return torch.device("mps")
    return torch.device("cpu")


def report_resources(device: torch.device, step_seconds: float) -> None:
    peak = 0.0
    if device.type == "cuda":
        peak = torch.cuda.max_memory_allocated(device) / 2**20
    elif device.type == "mps":
        peak = torch.mps.driver_allocated_memory() / 2**20
    print(f"resources: peak_memory_mb={peak:.1f} step_ms={step_seconds * 1e3:.2f} "
          f"batch_size={BATCH_SIZE} device={device.type}", flush=True)


def to_model_range(x: torch.Tensor) -> torch.Tensor:
    """VAEs work in [0, 1]; GANs and diffusion in [-1, 1]."""
    return x if KIND == "vae" else x * 2 - 1


def to_unit(x: torch.Tensor) -> np.ndarray:
    x = x if KIND == "vae" else (x + 1) / 2
    return x.clamp(0, 1).float().cpu().numpy()


_INCEPTION = None


def inception_features(images: np.ndarray) -> np.ndarray:
    """Pool features [N, 2048] of torchvision's Inception-v3 (downloads its weights)."""
    global _INCEPTION
    import torchvision

    if _INCEPTION is None:
        net = torchvision.models.inception_v3(weights="DEFAULT", aux_logits=True)
        net.fc = nn.Identity()
        _INCEPTION = net.eval()
    out = []
    mean = torch.tensor([0.485, 0.456, 0.406]).view(1, 3, 1, 1)
    std = torch.tensor([0.229, 0.224, 0.225]).view(1, 3, 1, 1)
    with torch.no_grad():
        for i in range(0, len(images), 64):
            x = torch.from_numpy(images[i:i + 64])
            x = x.repeat(1, 3, 1, 1) if x.shape[1] == 1 else x[:, :3]
            x = nn.functional.interpolate(x, size=(299, 299), mode="bilinear")
            out.append(_INCEPTION((x - mean) / std).numpy())
    return np.concatenate(out)


def features(images: np.ndarray, kind: str) -> np.ndarray:
    return inception_features(images) if kind == "inception" else pixel_features(images)


def image_scores(fake: np.ndarray, real: np.ndarray, wanted: dict) -> dict:
    out, cache = {}, {}
    for name, kind in wanted.items():
        if kind not in cache:
            cache[kind] = (features(fake, kind), features(real, kind))
        f, r = cache[kind]
        out[name] = frechet_distance(f, r) if name.startswith("fid") else \
            kernel_distance(f, r)
    return out


def save_grid(images: np.ndarray, path: Path, live: bool = False) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    image_grid(images).save(path)
    if live:
        print(f"samples: {path}", flush=True)


def encode_png(image: np.ndarray) -> str:
    arr = (np.clip(image, 0, 1) * 255).astype(np.uint8)
    img = Image.fromarray(arr[0], "L") if arr.shape[0] == 1 else \
        Image.fromarray(arr[:3].transpose(1, 2, 0), "RGB")
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    return base64.b64encode(buf.getvalue()).decode()


# ======================================================================== VAE
def bottleneck(model: nn.Module):
    return next(m for m in model.modules() if hasattr(m, "prior_z"))


def vae_losses(model: nn.Module, x: torch.Tensor) -> tuple:
    out = model(x)
    if out.shape != x.shape:
        raise SystemExit(f"the decoder outputs {list(out.shape[1:])} but images are "
                         f"{list(x.shape[1:])}: the VAE must reconstruct its input")
    if VAE["recon"] == "bce":
        recon = nn.functional.binary_cross_entropy(out.clamp(1e-6, 1 - 1e-6), x,
                                                   reduction="none")
    else:
        recon = nn.functional.mse_loss(out, x, reduction="none")
    return recon.flatten(1).sum(1).mean(), bottleneck(model).kl, out


@torch.no_grad()
def vae_generate(model: nn.Module, n: int, seed: int, device: torch.device) -> np.ndarray:
    model.eval()
    rep = bottleneck(model)
    gen = torch.Generator(device="cpu").manual_seed(seed)
    rep.prior_z = torch.randn((n, *STATE["latent_shape"]), generator=gen).to(device)
    try:
        out = model(torch.zeros((n, *INPUT_SHAPE), device=device))
    finally:
        rep.prior_z = None
    return to_unit(out)



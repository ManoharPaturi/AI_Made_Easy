_PREDICTOR = None


def load_predictor(folder: str | Path = ".", device: str = "cpu") -> nn.Module:
    global _PREDICTOR
    with open(Path(folder) / INFERENCE_FILE, "rb") as fh:
        STATE.update(pickle.load(fh))
    model = build_model()
    model.load_state_dict(torch.load(Path(folder) / CHECKPOINT, map_location=device))
    _PREDICTOR = model.eval().to(device)
    return _PREDICTOR


def generate_images(model, n: int, seed: int, device, label=None, steps=None,
                    guidance=None) -> np.ndarray:
    if KIND == "vae":
        return vae_generate(model, n, seed, device)
    if KIND == "adversarial":
        return gan_generate(model, n, seed, device)
    unet = denoiser(model)
    labels = None
    if unet.num_classes:
        labels = sample_labels(unet, n) if label is None else torch.full((n,), int(label))
    return diffusion_sample(unet, n, seed, device, labels, steps, guidance)


@torch.no_grad()
def infer(raw: list) -> list[dict]:
    """Each request: a count, or {"n", "seed", "class" (name or index), "steps",
    "guidance"} -> {"images": [base64 PNG, ...]}."""
    if _PREDICTOR is None:
        raise RuntimeError("call load_predictor(folder) first")
    device = next(_PREDICTOR.parameters()).device
    results = []
    for item in raw:
        item = item if isinstance(item, dict) else {"n": int(item or 1)}
        n = max(1, min(int(item.get("n", 1)), 64))
        label = item.get("class")
        if isinstance(label, str):
            names = STATE.get("names", [])
            if label not in names:
                raise ValueError(f"unknown class {label!r}; classes: {names}")
            label = names.index(label)
        images = generate_images(_PREDICTOR, n, int(item.get("seed", 0)), device, label,
                                 item.get("steps"), item.get("guidance"))
        results.append({"images": [encode_png(img) for img in images]})
    return results



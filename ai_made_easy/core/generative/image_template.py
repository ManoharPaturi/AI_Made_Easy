def _dataset(graph: Graph) -> dict:
    node = dataset_of(graph)
    if node is None:
        return {"block": "data.synthetic_images", "kind": "shapes", "n_images": 2000,
                "image_size": 32, "channels": 1, "seed": 0, "val_fraction": 0.1}
    out = {"block": node.type_id, **dict(node.resolved_params())}
    for key in ("root", "path"):
        raw = out.get(key)
        if raw and not str(raw).startswith("~") and not Path(str(raw)).is_absolute():
            candidate = Path.cwd() / str(raw)
            if candidate.exists():
                out[key] = str(candidate)
    return out


def _metrics(graph: Graph) -> tuple[dict, int]:
    nodes = [n for n in graph.nodes.values() if n.type_id in ("eval.fid", "eval.kid")]
    if not nodes:
        return {"fid": "pixels"}, 500
    wanted = {GENERATIVE_METRICS[n.type_id]["key"]: n.resolved_params()["features"]
              for n in nodes}
    return wanted, max(int(n.resolved_params()["samples"]) for n in nodes)


def context(graph: Graph, framework: str) -> dict:
    from ai_made_easy.core.generative.helpers import DCGAN_INIT, DISCRIMINATOR
    from ai_made_easy.core.training.generate import own_loop_requirements

    if framework != "pytorch":
        raise CodegenError("generative models train with PyTorch: choose the PyTorch "
                           "framework")
    kind = generative_kind(graph)
    if kind not in KIND_LABELS:
        raise CodegenError("not an image-generation design")
    notes: list[str] = []
    dataset = _dataset(graph)
    if dataset_of(graph) is None:
        notes.append("no dataset block: training on generated shapes (Synthetic Images)")
    chain = graph.model_nodes()
    shapes = graph.infer_shapes()
    input_shape = list(shapes[chain[0].instance_id])
    image_shape = list(shapes[chain[-1].instance_id]) if kind == "adversarial" else input_shape
    _t, trainer = _picked(graph, ("train.trainer",))
    trainer = cat.resolved("train.trainer", trainer)
    _l, loader = _picked(graph, ("prep.dataloader",))
    opt, opt_params = _picked(graph, cat.OPTIMIZER_IDS)
    optimizer = (DEFAULT_OPTIMIZERS[kind] if opt is None else
                 cat.render(opt.type_id, cat.resolved(opt.type_id, opt_params), "pytorch")
                 .replace("model.parameters()", "params"))
    losses = [n for n in graph.nodes.values() if n.type_id in cat.LOSS_IDS]
    recon = "bce" if any(n.type_id == "train.loss_bce" for n in losses) else "mse"
    if kind != "vae" and losses:
        notes.append("loss blocks are ignored: GANs and diffusion models use their own losses")
    _r, rep = _picked(graph, ("gen.reparameterize",))
    _d, disc = _picked(graph, ("gen.discriminator",))
    _s, sched = _picked(graph, ("gen.noise_scheduler",))
    if kind == "diffusion" and _s is None:
        sched = dict(DEFAULT_SCHEDULER)
        notes.append("no Noise Scheduler block: cosine schedule, 1000 steps, DDIM sampling")
    metrics, samples = _metrics(graph)
    model_code = generate(graph, "pytorch")
    name = sanitize_identifier(graph.name)
    extra = ("torchvision",) if "inception" in metrics.values() or \
        dataset["block"] == "data.torchvision" else ()
    return {
        "title": graph.name, "filename": f"{name}_train_pytorch.py", "name": name,
        "kind": kind, "kind_label": KIND_LABELS[kind], "notes": notes,
        "requirements": own_loop_requirements(model_code, extra),
        "data_comment": _data_comment(dataset), "dataset": dataset,
        "input_shape": input_shape, "image_shape": image_shape, "trainer": trainer,
        "batch_size": int(loader.get("batch_size") or 0) or int(trainer["batch_size"]),
        "metrics": metrics, "metric_samples": samples,
        "vae": {"beta": float(rep.get("beta", 1.0)), "kl_warmup": int(rep.get("kl_warmup", 0)),
                "recon": recon},
        "gan": {k: disc[k] for k in ("width", "norm", "spectral_norm", "loss", "gp_weight",
                                     "d_steps", "lr", "beta1")} if disc else {},
        "diffusion": {k: sched[k] for k in ("timesteps", "schedule", "sampler",
                                            "sample_steps", "guidance", "cond_dropout",
                                            "ema", "sample_every")} if sched else {},
        "model_code": _strip_main(model_code),
        "disc_code": ("" if kind != "adversarial" else DISCRIMINATOR
                      if "def dcgan_init" in model_code else DCGAN_INIT + "\n\n" + DISCRIMINATOR),
        "data_code": runtime.DATA_CODE, "metrics_code": runtime.METRICS_CODE,
        "plot_code": runtime.PLOT_CODE, "optimizer_expr": optimizer,
    }


def _data_comment(dataset: dict) -> str:
    if dataset["block"] == "data.synthetic_images":
        return (f"{dataset['n_images']} generated {dataset['kind']} images "
                f"({dataset['image_size']} px)")
    if dataset["block"] == "data.torchvision":
        return f"torchvision {dataset['dataset']}"
    return f"images under {dataset.get('root')}"


def render(graph: Graph, _spec, framework: str) -> str:
    return _env.from_string(TEMPLATE).render(**context(graph, framework))

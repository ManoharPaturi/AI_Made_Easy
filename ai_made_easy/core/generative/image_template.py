# ======================================================================== diffusion
def schedule(device) -> dict:
    t = DIFFUSION["timesteps"]
    if DIFFUSION["schedule"] == "linear":
        betas = torch.linspace(1e-4, 0.02, t, dtype=torch.float64)
    else:
        s = 0.008
        steps = torch.linspace(0, t, t + 1, dtype=torch.float64) / t
        cum = torch.cos((steps + s) / (1 + s) * math.pi / 2) ** 2
        betas = (1 - cum[1:] / cum[:-1]).clamp(0, 0.999)
    cum = torch.cumprod(1 - betas, 0)
    return {"betas": betas.float().to(device), "cum": cum.float().to(device)}


def denoiser(model: nn.Module):
    return next(m for m in model.modules() if getattr(m, "is_denoiser", False))


def diffusion_loss(unet, x0, labels, sched) -> torch.Tensor:
    t = torch.randint(0, DIFFUSION["timesteps"], (len(x0),), device=x0.device)
    noise = torch.randn_like(x0)
    a = sched["cum"][t].view(-1, 1, 1, 1)
    xt = a.sqrt() * x0 + (1 - a).sqrt() * noise
    y = None
    if unet.num_classes:
        y = labels.clone()
        y[torch.rand(len(y), device=y.device) < DIFFUSION["cond_dropout"]] = unet.num_classes
    return nn.functional.mse_loss(unet(xt, t, y), noise)


def guided_eps(unet, x, t, y, guidance) -> torch.Tensor:
    tt = torch.full((len(x),), int(t), device=x.device, dtype=torch.long)
    if not unet.num_classes or y is None or guidance == 1.0:
        return unet(x, tt, y)
    null = torch.full_like(y, unet.num_classes)
    both = unet(torch.cat([x, x]), torch.cat([tt, tt]), torch.cat([y, null]))
    cond, uncond = both.chunk(2)
    return uncond + guidance * (cond - uncond)


@torch.no_grad()
def diffusion_sample(unet, n: int, seed: int, device, labels=None, steps=None,
                     guidance=None, sampler=None) -> np.ndarray:
    unet.eval()
    sched = schedule(device)
    steps = int(steps or DIFFUSION["sample_steps"])
    guidance = float(DIFFUSION["guidance"] if guidance is None else guidance)
    sampler = sampler or DIFFUSION["sampler"]
    g = torch.Generator(device="cpu").manual_seed(seed)
    out = []
    for start in range(0, n, 128):
        m = min(128, n - start)
        x = torch.randn((m, *IMAGE_SHAPE), generator=g).to(device)
        y = None if labels is None else labels[start:start + m].to(device)
        if sampler == "ddpm":
            for t in range(DIFFUSION["timesteps"] - 1, -1, -1):
                eps = guided_eps(unet, x, t, y, guidance)
                beta, cum = sched["betas"][t], sched["cum"][t]
                prev = sched["cum"][t - 1] if t > 0 else torch.tensor(1.0, device=device)
                mean = (x - beta / (1 - cum).sqrt() * eps) / (1 - beta).sqrt()
                if t > 0:
                    var = beta * (1 - prev) / (1 - cum)
                    mean = mean + var.sqrt() * torch.randn(x.shape, generator=g).to(device)
                x = mean
        else:
            times = np.linspace(DIFFUSION["timesteps"] - 1, 0, steps).round().astype(int)
            for i, t in enumerate(times):
                eps = guided_eps(unet, x, t, y, guidance)
                a = sched["cum"][t]
                prev = sched["cum"][times[i + 1]] if i + 1 < len(times) else \
                    torch.tensor(1.0, device=device)
                x0 = ((x - (1 - a).sqrt() * eps) / a.sqrt()).clamp(-1, 1)
                x = prev.sqrt() * x0 + (1 - prev).sqrt() * eps
        out.append(x)
    return to_unit(torch.cat(out))


def sample_labels(unet, n: int):
    if not unet.num_classes:
        return None
    return torch.arange(n) % unet.num_classes


@torch.no_grad()
def diffusion_val_loss(unet, val_x, val_y, sched, device) -> float:
    unet.eval()
    torch.manual_seed(SEED)    # the same timesteps and noise every epoch
    total, n = 0.0, 0
    for start in range(0, len(val_x), 256):
        x0 = to_model_range(val_x[start:start + 256].to(device))
        total += diffusion_loss(unet, x0, val_y[start:start + 256].to(device), sched).item() \
            * len(x0)
        n += len(x0)
    return total / max(n, 1)


def train_diffusion(model, train_x, val_x, train_y, val_y, device):
    unet = denoiser(model)
    ema = copy.deepcopy(unet).eval() if DIFFUSION["ema"] > 0 else unet
    params = [p for p in model.parameters() if p.requires_grad]
    optimizer = {{ optimizer_expr }}
    sched = schedule(device)
    best, best_state, updates = math.inf, None, 0
    for epoch in range(1, EPOCHS + 1):
        unet.train()
        started, total, n = time.time(), 0.0, 0
        order = torch.randperm(len(train_x))
        for start in range(0, len(train_x), BATCH_SIZE):
            idx = order[start:start + BATCH_SIZE]
            x0 = to_model_range(train_x[idx].to(device))
            loss = diffusion_loss(unet, x0, train_y[idx].to(device), sched)
            if not torch.isfinite(loss):
                raise SystemExit(f"the loss became {float(loss)}: lower the learning rate")
            optimizer.zero_grad(set_to_none=True)
            loss.backward()
            if GRAD_CLIP > 0:
                nn.utils.clip_grad_norm_(params, GRAD_CLIP)
            optimizer.step()
            if ema is not unet:   # EMA with warm-up: early averages follow the weights
                updates += 1
                decay = min(DIFFUSION["ema"], (1 + updates) / (10 + updates))
                with torch.no_grad():
                    for e, p in zip(ema.parameters(), unet.parameters()):
                        e.lerp_(p, 1 - decay)
                    for e, b in zip(ema.buffers(), unet.buffers()):
                        e.copy_(b)
            total += loss.item() * len(x0)
            n += len(x0)
        if epoch == 1:
            report_resources(device, (time.time() - started) / max(1, -(-n // BATCH_SIZE)))
        val_loss = diffusion_val_loss(ema, val_x, val_y, sched, device)
        extra = ""
        if epoch % DIFFUSION["sample_every"] == 0 or epoch == EPOCHS:
            grid = diffusion_sample(ema, 32, SEED, device, sample_labels(ema, 32))
            save_grid(grid, LIVE_DIR / f"epoch_{epoch:03d}.png", live=True)
            k = min(METRIC_SAMPLES, 200)
            fake = diffusion_sample(ema, k, SEED + 1, device, sample_labels(ema, k))
            fid = image_scores(fake, STATE["real"], {"fid_pixels": "pixels"})["fid_pixels"]
            extra = f" val_fid_pixels={fid:.4f}"
        print(f"epoch {epoch}/{EPOCHS} train_loss={total / n:.4f} val_loss={val_loss:.4f}"
              f"{extra} ({time.time() - started:.1f}s)", flush=True)
        if val_loss < best:
            best = val_loss
            best_state = copy.deepcopy(ema.state_dict())
    unet.load_state_dict(best_state)
    return model



def _comment(dataset: dict) -> str:
    block = dataset["block"]
    if block == "data.synthetic_text":
        return f"{dataset['n_sentences']} generated sentences (bytes)"
    if block == "data.synthetic_pairs":
        return f"{dataset['n_pairs']} generated '{dataset['task']}' pairs"
    return str(dataset.get("path"))



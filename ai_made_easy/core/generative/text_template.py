def load_predictor(folder: str | Path = ".", device: str = "cpu") -> nn.Module:
    global _PREDICTOR
    with open(Path(folder) / INFERENCE_FILE, "rb") as fh:
        STATE.update(pickle.load(fh))
    model = build_model()
    model.load_state_dict(torch.load(Path(folder) / CHECKPOINT, map_location=device))
    _PREDICTOR = model.eval().to(device)
    return _PREDICTOR


@torch.no_grad()
def infer(raw: list) -> list[dict]:
    """Language model: a prompt, or {"prompt", "max_new_tokens", "temperature", "top_k",
    "seed"} -> {"text"}. Seq2seq: a source text (or {"source"}) -> {"text"}."""
    if _PREDICTOR is None:
        raise RuntimeError("call load_predictor(folder) first")
    device = next(_PREDICTOR.parameters()).device
    if KIND == "seq2seq":
        sources = [str(item["source"]) if isinstance(item, dict) else str(item) for item in raw]
        return [{"text": t} for t in translate(_PREDICTOR, sources, device)]
    results = []
    for item in raw:
        item = item if isinstance(item, dict) else {"prompt": str(item)}
        tokens = max(1, min(int(item.get("max_new_tokens", SAMPLE_TOKENS)), 2000))
        results.append({"text": lm_generate(_PREDICTOR, str(item.get("prompt", "")), tokens,
                                            float(item.get("temperature", 0.8)),
                                            int(item.get("top_k", 40)),
                                            int(item.get("seed", 0)))})
    return results



def pick_device() -> torch.device:
    if DEVICE != "auto":
        return torch.device(DEVICE)
    if torch.cuda.is_available():
        return torch.device("cuda")
    if torch.backends.mps.is_available():
        return torch.device("mps")
    return torch.device("cpu")


def report_resources(device: torch.device, step_seconds: float) -> None:
    peak = 0.0
    if device.type == "cuda":
        peak = torch.cuda.max_memory_allocated(device) / 2**20
    elif device.type == "mps":
        peak = torch.mps.driver_allocated_memory() / 2**20
    print(f"resources: peak_memory_mb={peak:.1f} step_ms={step_seconds * 1e3:.2f} "
          f"batch_size={BATCH_SIZE} device={device.type}", flush=True)


def write_samples(lines: list, path: Path, live: bool = False) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n\n".join(lines) + "\n", encoding="utf-8")
    if live:
        print(f"samples: {path}", flush=True)


# ======================================================================== language model
CONTEXT = INPUT_SHAPE[0]


def lm_batch(data: torch.Tensor, n: int, device) -> tuple:
    starts = torch.randint(0, len(data) - CONTEXT - 1, (n,))
    x = torch.stack([data[s:s + CONTEXT] for s in starts])
    y = torch.stack([data[s + 1:s + CONTEXT + 1] for s in starts])
    return x.to(device), y.to(device)


@torch.no_grad()
def lm_loss(model, data: torch.Tensor, device) -> float:
    """Mean next-byte cross-entropy over non-overlapping windows."""
    model.eval()
    total, count = 0.0, 0
    windows = (len(data) - 1) // CONTEXT
    for start in range(0, windows, 64):
        idx = torch.arange(start, min(windows, start + 64)) * CONTEXT
        x = torch.stack([data[s:s + CONTEXT] for s in idx]).to(device)
        y = torch.stack([data[s + 1:s + CONTEXT + 1] for s in idx]).to(device)
        logits = model(x)
        total += nn.functional.cross_entropy(logits.reshape(-1, logits.shape[-1]),
                                             y.reshape(-1), reduction="sum").item()
        count += y.numel()
    return total / max(count, 1)


@torch.no_grad()
def lm_generate(model, prompt: str, tokens: int, temperature: float = 0.8, top_k: int = 40,
                seed: int = 0) -> str:
    model.eval()
    device = next(model.parameters()).device
    g = torch.Generator(device="cpu").manual_seed(seed)
    ids = list(encode_bytes(prompt)) or [10]
    for _ in range(tokens):
        window = ids[-CONTEXT:]
        window = [10] * (CONTEXT - len(window)) + window   # left-pad with newlines
        logits = model(torch.tensor([window], device=device))[0, -1].float().cpu()
        logits = logits / max(temperature, 1e-4)
        if top_k:
            kth = torch.topk(logits, min(top_k, logits.numel())).values[-1]
            logits[logits < kth] = -math.inf
        ids.append(int(torch.multinomial(logits.softmax(-1), 1, generator=g)))
    return decode_bytes(ids[len(encode_bytes(prompt)):])


def lm_prompts(text: str) -> list[str]:
    lines = [ln for ln in text.splitlines() if len(ln) > 8]
    return [ln[: max(4, len(ln) // 4)] for ln in lines[:3]] or ["The "]



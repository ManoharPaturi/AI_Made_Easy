# ======================================================================== seq2seq
TARGET_LEN = OUTPUT_SHAPE[0]


def seq2seq_module(model):
    return next(m for m in model.modules() if getattr(m, "is_seq2seq", False))


def encode_split(pairs: list) -> tuple:
    src = torch.from_numpy(np.stack([encode_pair(s, INPUT_SHAPE[0], False) for s, _ in pairs]))
    tgt = torch.from_numpy(np.stack([encode_pair(t, TARGET_LEN + 1, True) for _, t in pairs]))
    return src, tgt


@torch.no_grad()
def translate(model, sources: list, device) -> list[str]:
    s2s = seq2seq_module(model).eval()
    out = []
    for i in range(0, len(sources), 128):
        src = torch.from_numpy(np.stack([encode_pair(s, INPUT_SHAPE[0], False)
                                         for s in sources[i:i + 128]])).to(device)
        for row in s2s.generate(src).cpu().tolist():
            ids = row[: row.index(EOS)] if EOS in row else row
            out.append(decode_bytes(ids))
    return out



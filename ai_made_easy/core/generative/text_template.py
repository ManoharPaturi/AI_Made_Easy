              f"val_loss={val_loss:.4f} val_perplexity={math.exp(min(val_loss, 50)):.4f} "
              f"val_bits_per_byte={val_loss / math.log(2):.4f} "
              f"lr={optimizer.param_groups[0]['lr']:.3g} ({time.time() - started:.1f}s)",

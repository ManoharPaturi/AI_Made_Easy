def _dataset(graph: Graph) -> dict:
    node = dataset_of(graph)
    if node is None:
        return {"block": "data.synthetic_images", "kind": "shapes", "n_images": 64,
                "image_size": 64, "channels": 3, "seed": 0, "val_fraction": 0.1}
    out = {"block": node.type_id, **dict(node.resolved_params())}
    for key in ("root", "path"):
        raw = out.get(key)
        if raw and not str(raw).startswith("~") and not Path(str(raw)).is_absolute():
            candidate = Path.cwd() / str(raw)
            if candidate.exists():
                out[key] = str(candidate)
    return out


def context(graph: Graph, framework: str) -> dict:
    if framework != "pytorch":
        raise CodegenError("Stable Diffusion trains with PyTorch: choose the PyTorch framework")
    if generative_kind(graph) != "text_to_image":
        raise CodegenError("not a Stable Diffusion LoRA design")
    notes: list[str] = []
    dataset = _dataset(graph)
    if dataset_of(graph) is None:
        notes.append("no dataset block: training on generated shapes captioned by their class")
    _n, sd = _picked(graph, ("gen.sd_lora",))
    sd["resolution"] = int(sd["resolution"])
    _t, trainer = _picked(graph, ("train.trainer",))
    trainer = cat.resolved("train.trainer", trainer)
    _l, loader = _picked(graph, ("prep.dataloader",))
    opt, opt_params = _picked(graph, cat.OPTIMIZER_IDS)
    optimizer = (DEFAULT_OPTIMIZER if opt is None else
                 cat.render(opt.type_id, cat.resolved(opt.type_id, opt_params), "pytorch")
                 .replace("model.parameters()", "params"))
    if any(n.type_id in cat.LOSS_IDS for n in graph.nodes.values()):
        notes.append("loss blocks are ignored: the adapters train on the denoising loss")
    metric_nodes = [n for n in graph.nodes.values()
                    if n.type_id in ("eval.fid", "eval.kid")]
    metrics = {GENERATIVE_METRICS[n.type_id]["key"]: n.resolved_params()["features"]
               for n in metric_nodes}
    samples = max([int(n.resolved_params()["samples"]) for n in metric_nodes] or [0])
    name = sanitize_identifier(graph.name)
    model = ("tiny random Stable Diffusion (offline check)" if sd["weights"] == "none"
             else sd["base_model"])
    return {
        "title": graph.name, "filename": f"{name}_train_pytorch.py", "name": name,
        "notes": notes, "requirements": "torch, diffusers, peft, transformers, pillow",
        "data_comment": _data_comment(dataset),
        "model_comment": f"{model} + LoRA rank {sd['rank']} on the UNet attention",
        "dataset": dataset, "sd": sd, "trainer": trainer,
        "batch_size": int(loader.get("batch_size") or 0) or int(trainer["batch_size"]),
        "metrics": metrics, "metric_samples": samples, "is_splits": 10,
        "data_code": runtime.DATA_CODE, "metrics_code": runtime.METRICS_CODE,
        "plot_code": runtime.PLOT_CODE, "optimizer_expr": optimizer,
    }


def _data_comment(dataset: dict) -> str:
    if dataset["block"] == "data.synthetic_images":
        return f"{dataset['n_images']} generated {dataset['kind']} images"
    return f"images under {dataset.get('root')}"


def render(graph: Graph, _spec, framework: str) -> str:
    return _env.from_string(TEMPLATE).render(**context(graph, framework))

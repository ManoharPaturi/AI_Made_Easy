def image_scores(fake: np.ndarray, real: np.ndarray, wanted: dict) -> dict:
    out = {}
    for name, kind in wanted.items():
        if kind != "pixels":
            raise SystemExit(f"{name} with Inception features is not available for Stable "
                             "Diffusion LoRA runs: use features = pixels")
        f, r = pixel_features(fake), pixel_features(real)
        out[name] = frechet_distance(f, r) if name.startswith("fid") else kernel_distance(f, r)
    return out



"""Training scripts for text-to-image LoRA fine-tuning of Stable Diffusion (diffusers + peft).

The script freezes the pretrained UNet, VAE and text encoder, adds low-rank adapters to
the UNet's attention projections and trains them on the user's images, each captioned by
a prompt template ("a photo of {class}" with the image's class folder). Every epoch it
saves a grid of samples for the sample prompts (shown live in the app); at the end it
saves the LoRA weights in the diffusers format (``load_lora_weights`` reads them) and the
``load_predictor`` / ``infer`` functions turn prompts into images. With weights = none a
tiny randomly initialised Stable Diffusion is built instead: nothing is downloaded, so a
design can be checked end to end on any machine.
"""

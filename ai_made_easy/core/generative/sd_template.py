# ======================================================================== shared
def pick_device() -> torch.device:
    if DEVICE != "auto":
        return torch.device(DEVICE)
    if torch.cuda.is_available():
        return torch.device("cuda")
    if torch.backends.mps.is_available():
        return torch.device("mps")
    return torch.device("cpu")


def report_resources(device: torch.device, step_seconds: float) -> None:
    peak = 0.0
    if device.type == "cuda":
        peak = torch.cuda.max_memory_allocated(device) / 2**20
    elif device.type == "mps":
        peak = torch.mps.driver_allocated_memory() / 2**20
    print(f"resources: peak_memory_mb={peak:.1f} step_ms={step_seconds * 1e3:.2f} "
          f"batch_size={BATCH_SIZE} device={device.type}", flush=True)


def save_grid(images: np.ndarray, path: Path, live: bool = False) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    image_grid(images, columns=4, scale=1 if images.shape[-1] >= 128 else 0).save(path)
    if live:
        print(f"samples: {path}", flush=True)


def encode_png(image: np.ndarray) -> str:
    arr = (np.clip(image, 0, 1) * 255).astype(np.uint8).transpose(1, 2, 0)
    buf = io.BytesIO()
    Image.fromarray(arr, "RGB").save(buf, format="PNG")
    return base64.b64encode(buf.getvalue()).decode()


# ======================================================================== model
class ByteTokenizer:
    """weights = none: prompts as UTF-8 bytes between BOS / EOS (no tokenizer download)."""

    model_max_length = 32

    def __call__(self, prompts: list) -> torch.Tensor:
        ids = torch.zeros(len(prompts), self.model_max_length, dtype=torch.long)
        for i, prompt in enumerate(prompts):
            data = list(prompt.encode("utf-8"))[: self.model_max_length - 2]
            ids[i, : len(data) + 2] = torch.tensor([256, *data, 257])
        return ids


def tiny_components() -> dict:
    """A miniature Stable Diffusion (random weights) with the real architecture."""
    from diffusers import AutoencoderKL, DDPMScheduler, UNet2DConditionModel
    from transformers import CLIPTextConfig, CLIPTextModel

    torch.manual_seed(SEED)
    return {
        "unet": UNet2DConditionModel(
            sample_size=SIDE // 2, in_channels=4, out_channels=4,
            layers_per_block=1, block_out_channels=(32, 64), norm_num_groups=8,
            down_block_types=("CrossAttnDownBlock2D", "DownBlock2D"),
            up_block_types=("UpBlock2D", "CrossAttnUpBlock2D"), cross_attention_dim=32,
            attention_head_dim=4),
        "vae": AutoencoderKL(
            in_channels=3, out_channels=3, latent_channels=4, block_out_channels=(32, 64),
            down_block_types=("DownEncoderBlock2D",) * 2, norm_num_groups=8,
            up_block_types=("UpDecoderBlock2D",) * 2, sample_size=SIDE),
        "text_encoder": CLIPTextModel(CLIPTextConfig(
            vocab_size=258, hidden_size=32, intermediate_size=64, num_hidden_layers=2,
            num_attention_heads=4, max_position_embeddings=32, bos_token_id=256,
            eos_token_id=257, pad_token_id=0)),
        "tokenizer": ByteTokenizer(),
        "scheduler": DDPMScheduler(num_train_timesteps=1000),
    }


def load_components() -> dict:
    """The frozen base model: pretrained from the Hugging Face Hub, or the tiny one."""
    if SD["weights"] == "none":
        parts = tiny_components()
        if Path(BASE_FILE).exists():
            state = torch.load(BASE_FILE, map_location="cpu")
            for key in ("unet", "vae", "text_encoder"):
                parts[key].load_state_dict(state[key])
        return parts
    from diffusers import AutoencoderKL, DDPMScheduler, UNet2DConditionModel
    from transformers import CLIPTextModel, CLIPTokenizer

    repo = SD["base_model"]
    return {"unet": UNet2DConditionModel.from_pretrained(repo, subfolder="unet"),
            "vae": AutoencoderKL.from_pretrained(repo, subfolder="vae"),
            "text_encoder": CLIPTextModel.from_pretrained(repo, subfolder="text_encoder"),
            "tokenizer": CLIPTokenizer.from_pretrained(repo, subfolder="tokenizer"),
            "scheduler": DDPMScheduler.from_pretrained(repo, subfolder="scheduler")}


def add_lora(unet) -> list:
    """Low-rank adapters on the attention projections; returns the trainable parameters."""
    from peft import LoraConfig

    unet.requires_grad_(False)
    unet.add_adapter(LoraConfig(r=SD["rank"], lora_alpha=SD["alpha"],
                                init_lora_weights="gaussian",
                                target_modules=["to_k", "to_q", "to_v", "to_out.0"]))
    params = [p for p in unet.parameters() if p.requires_grad]
    for p in params:   # adapters train in float32 even when the base runs in half precision
        p.data = p.data.float()
    return params


def tokenize(parts: dict, prompts: list) -> torch.Tensor:
    tok = parts["tokenizer"]
    if isinstance(tok, ByteTokenizer):
        return tok(prompts)
    return tok(prompts, padding="max_length", max_length=tok.model_max_length,
               truncation=True, return_tensors="pt").input_ids


@torch.no_grad()
def embed(parts: dict, prompts: list, device) -> torch.Tensor:
    return parts["text_encoder"](tokenize(parts, prompts).to(device))[0]


def latent_scale(parts: dict) -> float:
    return float(parts["vae"].config.scaling_factor)


# ======================================================================== data
def prompts_for(labels: np.ndarray, names: list) -> list:
    template = SD["prompt"]
    return [template.replace("{class}", names[int(c)].replace("_", " ")) if names
            else template.replace("{class}", "").strip() for c in labels]


def sample_prompts(names: list) -> list:
    custom = [p.strip() for p in SD["sample_prompts"].split("|") if p.strip()]
    if custom:
        return custom[:8]
    if names and "{class}" in SD["prompt"]:
        return [SD["prompt"].replace("{class}", n.replace("_", " ")) for n in names][:8]
    return [SD["prompt"].replace("{class}", "").strip()]


# ======================================================================== sampling
@torch.no_grad()
def generate(parts: dict, prompts: list, device, steps: int | None = None,
             guidance: float | None = None, seed: int = 0) -> np.ndarray:
    """Images [N, 3, R, R] in [0, 1] (DDIM with classifier-free guidance)."""
    from diffusers import DDIMScheduler

    unet, vae = parts["unet"], parts["vae"]
    unet.eval()
    sampler = DDIMScheduler.from_config(parts["scheduler"].config)
    sampler.set_timesteps(steps or SD["sample_steps"])
    guidance = SD["guidance"] if guidance is None else guidance
    dtype = next(unet.parameters()).dtype
    cond = embed(parts, prompts, device).to(dtype)
    uncond = embed(parts, [""] * len(prompts), device).to(dtype)
    factor = 2 ** (len(vae.config.block_out_channels) - 1)
    g = torch.Generator(device="cpu").manual_seed(seed)
    side = SIDE // factor
    latents = torch.randn(len(prompts), unet.config.in_channels, side, side,
                          generator=g).to(device, dtype) * sampler.init_noise_sigma
    for t in sampler.timesteps:
        x = sampler.scale_model_input(torch.cat([latents, latents]), t)
        noise = unet(x, t, torch.cat([uncond, cond])).sample
        free, text = noise.chunk(2)
        latents = sampler.step(free + guidance * (text - free), t, latents).prev_sample
    images = vae.decode(latents / latent_scale(parts)).sample
    return ((images.float() + 1) / 2).clamp(0, 1).cpu().numpy()


# ======================================================================== training
def train(parts: dict, images: torch.Tensor, prompts: list, names: list, device) -> list:
    unet, vae, text_encoder = parts["unet"], parts["vae"], parts["text_encoder"]
    half = MIXED_PRECISION and device.type == "cuda"
    dtype = torch.float16 if half else torch.float32
    for module in (vae, text_encoder, unet):
        module.requires_grad_(False)
        if half:   # the frozen base in float16 halves its memory
            module.to(device, dtype=dtype)
        else:
            module.to(device)
    params = add_lora(unet)
    unet.to(device)
    print(f"parameters: {sum(p.numel() for p in params):,} trainable (LoRA rank "
          f"{SD['rank']}) of {sum(p.numel() for p in unet.parameters()):,} in the UNet")
    optimizer = {{ optimizer_expr }}
    scheduler = parts["scheduler"]
    target_kind = scheduler.config.get("prediction_type", "epsilon")
    scaler = torch.amp.GradScaler("cuda", enabled=half)
    shown = sample_prompts(names)
    losses = []
    steps = max(1, math.ceil(len(images) / BATCH_SIZE))
    for epoch in range(1, EPOCHS + 1):
        unet.train()
        started, total = time.time(), 0.0
        order = torch.randperm(len(images))
        optimizer.zero_grad(set_to_none=True)
        for step in range(steps):
            idx = order[step * BATCH_SIZE:(step + 1) * BATCH_SIZE]
            pixels = (images[idx] * 2 - 1).to(device, dtype)
            with torch.no_grad():
                latents = vae.encode(pixels).latent_dist.sample() * latent_scale(parts)
                cond = embed(parts, [prompts[int(i)] for i in idx], device)
            noise = torch.randn_like(latents)
            t = torch.randint(0, scheduler.config.num_train_timesteps, (len(idx),),
                              device=device)
            noisy = scheduler.add_noise(latents, noise, t)
            target = (scheduler.get_velocity(latents, noise, t)
                      if target_kind == "v_prediction" else noise)
            with torch.autocast(device_type=device.type, dtype=torch.float16, enabled=half):
                pred = unet(noisy, t, cond).sample
            loss = nn.functional.mse_loss(pred.float(), target.float())
            if not torch.isfinite(loss):
                raise SystemExit(f"the loss became {float(loss)}: lower the learning rate")
            scaler.scale(loss / ACCUM_STEPS).backward()
            if (step + 1) % ACCUM_STEPS == 0 or step + 1 == steps:
                scaler.unscale_(optimizer)
                nn.utils.clip_grad_norm_(params, GRAD_CLIP)
                scaler.step(optimizer)
                scaler.update()
                optimizer.zero_grad(set_to_none=True)
            total += loss.item()
        if epoch == 1:
            report_resources(device, (time.time() - started) / steps)
        losses.append(total / steps)
        if epoch % SD["sample_every"] == 0 or epoch == EPOCHS:
            save_grid(generate(parts, shown, device, seed=SEED),
                      LIVE_DIR / f"epoch_{epoch:03d}.png", live=True)
        print(f"epoch {epoch}/{EPOCHS} train_loss={losses[-1]:.4f} "
              f"lr={optimizer.param_groups[0]['lr']:.3g} ({time.time() - started:.1f}s)",
              flush=True)
    return losses


def save_lora(parts: dict) -> None:
    from diffusers import StableDiffusionPipeline
    from diffusers.utils import convert_state_dict_to_diffusers
    from peft.utils import get_peft_model_state_dict

    layers = convert_state_dict_to_diffusers(get_peft_model_state_dict(parts["unet"]))
    StableDiffusionPipeline.save_lora_weights(str(LORA_DIR), unet_lora_layers=layers,
                                              safe_serialization=True)



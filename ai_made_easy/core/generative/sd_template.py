def load_predictor(folder: str | Path = ".", device: str | None = None) -> dict:
    """The base model with the trained LoRA adapters."""
    global _PREDICTOR, BASE_FILE
    folder = Path(folder)
    with open(folder / INFERENCE_FILE, "rb") as fh:
        STATE.update(pickle.load(fh))
    BASE_FILE = str(folder / Path(BASE_FILE).name)
    target = torch.device(device) if device else pick_device()
    parts = load_components()
    parts["unet"].load_lora_adapter(str(folder / LORA_DIR), prefix="unet",
                                    weight_name="pytorch_lora_weights.safetensors")
    for key in ("unet", "vae", "text_encoder"):
        parts[key].to(target).eval()
    _PREDICTOR = {"parts": parts, "device": target}
    return _PREDICTOR


def infer(raw: list) -> list[dict]:
    """A prompt, or {"prompt", "steps", "guidance", "seed"} -> {"image": base64 PNG}."""
    if _PREDICTOR is None:
        raise RuntimeError("call load_predictor(folder) first")
    out = []
    for item in raw:
        item = item if isinstance(item, dict) else {"prompt": str(item)}
        steps = max(1, min(int(item.get("steps", SD["sample_steps"])), 200))
        image = generate(_PREDICTOR["parts"], [str(item.get("prompt", ""))],
                         _PREDICTOR["device"], steps, float(item.get("guidance", SD["guidance"])),
                         int(item.get("seed", 0)))[0]
        out.append({"image": encode_png(image), "shape": list(image.shape)})
    return out



def _ints(text) -> list[int]:  # noqa: ANN001
    return [int(float(v)) for v in str(text or "").split(",") if v.strip()]


def context(graph: Graph, framework: str) -> dict:
    from ai_made_easy.core.training import catalog as cat
    from ai_made_easy.core.training.generate import own_loop_requirements

    if framework != "pytorch":
        raise CodegenError("reinforcement learning trains with PyTorch (stable-baselines3): "
                           "choose the PyTorch framework")
    env = env_node(graph)
    ep = env.resolved_params() if env is not None else {"env_id": "CartPole-v1",
                                                        "custom_id": "", "n_envs": 4, "seed": 0}
    env_id = ep["custom_id"] if ep["env_id"] == "custom" else ep["env_id"]
    info = observation_info(graph)
    atari = atari_config(graph)
    algo = algorithm_node(graph)
    if algo is None:
        from ai_made_easy.core.registry import get_registry

        type_id = "rl.ppo"
        ap = {p.name: p.default for p in get_registry().get(type_id).params}
    else:
        type_id, ap = algo.type_id, dict(algo.resolved_params())
    if type_id not in ALGORITHMS:
        raise CodegenError(f"unknown algorithm {type_id}")
    trainer = next((n for n in graph.nodes.values() if n.type_id == "train.trainer"), None)
    device = cat.resolved("train.trainer", dict(trainer.params) if trainer else {})["device"]
    chain = graph.model_nodes()
    shapes = graph.infer_shapes()
    model_code = generate(graph, "pytorch")
    name = sanitize_identifier(graph.name)
    out_shape = list(shapes[chain[-1].instance_id])
    return {
        "title": graph.name, "filename": f"{name}_train_pytorch.py", "name": name,
        "env_id": env_id or "CartPole-v1", "n_envs": int(ep["n_envs"]), "seed": int(ep["seed"]),
        "algo": CLASSES[type_id],
        "hparams": {k: v for k, v in ap.items() if k not in LOOP},
        "loop": {k: ap[k] for k in ("total_timesteps", "evaluations", "eval_episodes")},
        "head": _ints(ap.get("head")), "action_noise": float(ap.get("action_noise", 0.0)),
        "device": device, "input_shape": list(shapes[chain[0].instance_id]),
        "image_obs": bool(info and info[0] is not None and len(info[0]) == 3),
        "built_in": ep["env_id"] in BUILT_IN, "atari": atari,
        "env_module": str(ep.get("module") or "") if ep["env_id"] == "custom" else "",
        "features": int(out_shape[0]),
        "requirements": own_loop_requirements(model_code, ("gymnasium", "stable-baselines3",
                                                           *(("ale-py",) if atari else ()))),
        "model_code": _strip_main(model_code),
    }


def render(graph: Graph, _spec, framework: str) -> str:
    return _env.from_string(TEMPLATE).render(**context(graph, framework))


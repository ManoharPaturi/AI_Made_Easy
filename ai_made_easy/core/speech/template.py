def _dataset(graph: Graph) -> dict:
    node = dataset_of(graph)
    if node is None:
        return dict(DEFAULT_DATA)
    out = {"block": node.type_id, **dict(node.resolved_params())}
    raw = out.get("path")
    if raw and not str(raw).startswith("~") and not Path(str(raw)).is_absolute():
        candidate = Path.cwd() / str(raw)
        if candidate.exists():
            out["path"] = str(candidate)
    return out


TASK_LABELS = {"keywords": "keyword spotting", "transcripts": "speech recognition (CTC)",
               "tags": "audio tagging"}
OWN_LOSS = {"keywords": "train.loss_cross_entropy", "transcripts": "speech.loss_ctc",
            "tags": "train.loss_bce_logits"}


def context(graph: Graph, framework: str) -> dict:
    if framework != "pytorch":
        raise CodegenError("speech tasks train with PyTorch: choose the PyTorch framework")
    if speech_task(graph) is None:
        raise CodegenError("not a speech design")
    dataset = _dataset(graph)
    if dataset_of(graph) is None:
        dataset["task"] = "transcripts"   # only a CTC loss marks this design as speech
    task = dataset["task"]
    notes: list[str] = []
    if dataset_of(graph) is None:
        notes.append("no dataset block: training on generated tone-coded speech")
    losses = [n for n in graph.nodes.values() if n.type_id in cat.LOSS_IDS
              or n.type_id == "speech.loss_ctc"]
    for node in losses:
        if node.type_id != OWN_LOSS[task]:
            notes.append(f"{node.definition().display_name} is ignored: {TASK_LABELS[task]} "
                         "trains with its own loss")
    ce = next((dict(n.resolved_params()) for n in losses
               if n.type_id == "train.loss_cross_entropy"), {})
    ctc = next((dict(n.resolved_params()) for n in losses if n.type_id == "speech.loss_ctc"),
               {"zero_infinity": True})
    chain = graph.model_nodes()
    input_shape = list(graph.infer_shapes()[chain[0].instance_id])
    _t, trainer = _picked(graph, ("train.trainer",))
    trainer = cat.resolved("train.trainer", trainer)
    _l, loader = _picked(graph, ("prep.dataloader",))
    opt, opt_params = _picked(graph, cat.OPTIMIZER_IDS)
    optimizer = ("torch.optim.AdamW(params, lr=0.001)" if opt is None else
                 cat.render(opt.type_id, cat.resolved(opt.type_id, opt_params), "pytorch")
                 .replace("model.parameters()", "params"))
    sched, sched_params = _picked(graph, cat.SCHEDULER_IDS)
    name = sanitize_identifier(graph.name)
    rate = int(dataset["sample_rate"])
    model_code = generate(graph, "pytorch")
    from ai_made_easy.core.training.generate import own_loop_requirements

    return {
        "requirements": own_loop_requirements(model_code),
        "title": graph.name, "filename": f"{name}_train_pytorch.py", "name": name,
        "notes": notes, "data_comment": _data_comment(dataset), "task": task,
        "task_label": TASK_LABELS[task], "dataset": dataset, "sample_rate": rate,
        "n_samples": int(round(float(dataset["duration"]) * rate)),
        "label_smoothing": float(ce.get("label_smoothing", 0.0)),
        "zero_infinity": bool(ctc.get("zero_infinity", True)),
        "input_shape": input_shape, "trainer": trainer,
        "batch_size": int(loader.get("batch_size") or 0) or int(trainer["batch_size"]),
        "model_code": _strip_main(model_code),
        "data_code": runtime.DATA_CODE, "metrics_code": runtime.METRICS_CODE,
        "plot_code": runtime.PLOT_CODE, "optimizer_expr": optimizer,
        "scheduler_expr": (cat.render(sched.type_id, cat.resolved(sched.type_id, sched_params),
                                      "pytorch") if sched else None),
        "scheduler_step": cat.COMPONENTS[sched.type_id].meta["step"] if sched else None,
    }


def _data_comment(dataset: dict) -> str:
    if dataset["block"] == "data.synthetic_speech":
        return (f"{dataset['n_clips']} generated {dataset['task']} clips of "
                f"{dataset['duration']} s at {dataset['sample_rate']} Hz")
    return f"{dataset['path']} ({dataset['task']}, {dataset['sample_rate']} Hz)"


def render(graph: Graph, _spec, framework: str) -> str:
    return _env.from_string(TEMPLATE).render(**context(graph, framework))


def register() -> None:
    from ai_made_easy.core.training.generate import register_trainer

    register_trainer("speech", render, needs_spec=False)

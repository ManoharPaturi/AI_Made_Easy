def to_wave(item) -> np.ndarray:
    """A waveform list, {"waveform": [...], "sample_rate": n}, or WAV bytes / base64."""
    if isinstance(item, dict):
        wave = np.asarray(item["waveform"], np.float32)
        rate = int(item.get("sample_rate", SAMPLE_RATE))
    elif isinstance(item, (bytes, bytearray, str)):
        data = base64.b64decode(item) if isinstance(item, str) else bytes(item)
        wave, rate = decode_wav_bytes(data)
    else:
        wave, rate = np.asarray(item, np.float32).reshape(-1), SAMPLE_RATE
    return fit_length(resample(wave, rate, SAMPLE_RATE), N_SAMPLES)


@torch.no_grad()
def infer(raw: list) -> list[dict]:
    if _PREDICTOR is None:
        raise RuntimeError("call load_predictor(folder) first")
    device = next(_PREDICTOR.parameters()).device
    names = STATE["names"]
    waves = torch.from_numpy(np.stack([to_wave(item) for item in raw]))[:, None]
    results = []
    for pred in predict(_PREDICTOR, waves, device):
        if TASK == "keywords":
            i = int(np.argmax(pred))
            results.append({"label": names[i], "score": round(float(pred[i]), 4),
                            "probabilities": {n: round(float(v), 4)
                                              for n, v in zip(names, pred)}})
        elif TASK == "tags":
            results.append({"tags": [names[i] for i in np.flatnonzero(pred >= 0.5)],
                            "scores": {n: round(float(v), 4) for n, v in zip(names, pred)}})
        else:
            results.append({"text": pred})
    return results



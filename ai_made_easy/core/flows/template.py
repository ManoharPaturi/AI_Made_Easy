def density_2d(kind: str, n: int, noise: float, seed: int) -> np.ndarray:
    """Points from a 2-D toy distribution."""
    rng = np.random.default_rng(seed)
    if kind == "moons":
        t = rng.uniform(0, np.pi, n)
        upper = rng.random(n) < 0.5
        x = np.where(upper[:, None], np.stack([np.cos(t), np.sin(t)], 1),
                     np.stack([1 - np.cos(t), 0.5 - np.sin(t)], 1)) - [0.5, 0.25]
    elif kind == "circles":
        t = rng.uniform(0, 2 * np.pi, n)
        r = np.where(rng.random(n) < 0.5, 2.0, 1.0)
        x = np.stack([r * np.cos(t), r * np.sin(t)], 1)
    elif kind == "eight_gaussians":
        angle = rng.integers(0, 8, n) * np.pi / 4
        x = 2 * np.stack([np.cos(angle), np.sin(angle)], 1) + rng.normal(0, 0.1, (n, 2))
    elif kind == "checkerboard":
        x1 = rng.uniform(-2, 2, n)
        x2 = rng.uniform(0, 1, n) - 2 * rng.integers(0, 2, n) + np.floor(x1) % 2
        x = np.stack([x1, x2], 1)
    elif kind == "spiral":
        t = np.sqrt(rng.random(n)) * 3 * np.pi
        sign = np.where(rng.random(n) < 0.5, 1.0, -1.0)[:, None]
        x = sign * np.stack([-np.cos(t) * t, np.sin(t) * t], 1) / 3
    elif kind == "pinwheel":
        arms, radial, tangential, rate = 5, 0.3, 0.1, 0.25
        labels = rng.integers(0, arms, n)
        feats = rng.normal(0, 1, (n, 2)) * [radial, tangential] + [1.0, 0.0]
        angles = labels * 2 * np.pi / arms + rate * np.exp(feats[:, 0])
        rot = np.stack([np.cos(angles), -np.sin(angles), np.sin(angles), np.cos(angles)], 1)
        x = 2 * np.einsum("ni,nij->nj", feats, rot.reshape(n, 2, 2))
    else:
        raise SystemExit(f"unknown 2-D density {kind!r}")
    return (x + rng.normal(0, noise, x.shape)).astype(np.float32)


def density_images(kind: str, size: int, n: int, seed: int) -> np.ndarray:
    """8-bit greyscale images [N, 1, size, size]: rectangles and discs, bars, or blobs."""
    rng = np.random.default_rng(seed)
    yy, xx = np.mgrid[0:size, 0:size] + 0.5
    out = np.zeros((n, size, size), np.float32)
    for i in range(n):
        img = np.full((size, size), rng.uniform(0, 40))
        for _ in range(rng.integers(1, 4)):
            level = rng.uniform(120, 255)
            if kind == "bars":
                pos, width = rng.integers(0, size), rng.integers(1, max(2, size // 4))
                band = (np.abs(xx - pos) < width) if rng.random() < 0.5 else \
                    (np.abs(yy - pos) < width)
                img = np.where(band, level, img)
            elif kind == "blobs":
                cx, cy = rng.uniform(0, size, 2)
                r = rng.uniform(size / 8, size / 3)
                img = np.maximum(img, level * np.exp(-((xx - cx) ** 2 + (yy - cy) ** 2)
                                                     / (2 * r * r)))
            elif rng.random() < 0.5:
                x0, y0 = rng.integers(0, size - 2, 2)
                w, h = rng.integers(2, max(3, size // 2), 2)
                img[y0:y0 + h, x0:x0 + w] = level
            else:
                cx, cy = rng.uniform(1, size - 1, 2)
                r = rng.uniform(1.5, size / 3)
                img = np.where((xx - cx) ** 2 + (yy - cy) ** 2 < r * r, level, img)
        out[i] = img
    noise = rng.normal(0, 4, out.shape)
    return np.clip(out + noise, 0, 255).astype(np.uint8)[:, None]



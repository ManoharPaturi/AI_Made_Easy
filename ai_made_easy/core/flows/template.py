def image_picture(model: nn.Module, data: np.ndarray, path: Path, title: str,
                  live: bool = False) -> None:
    """Data images | samples from the flow, in two grids."""
    from PIL import Image, ImageDraw

    model.eval()
    drawn = sample(model, 32, seed=SEED)
    tile, cols, rows, pad = 3, 8, 4, 10
    h, w = IMAGE_SHAPE[1] * tile, IMAGE_SHAPE[2] * tile
    grid_w, grid_h = cols * (w + 2), rows * (h + 2)
    img = Image.new("RGB", (2 * grid_w + 3 * pad, grid_h + 2 * pad + 36), (24, 26, 30))
    draw = ImageDraw.Draw(img)
    for k, images in enumerate((data[:32], drawn)):
        ox = pad + k * (grid_w + pad)
        draw.text((ox, 4), ("data", "samples from the flow")[k], fill=(200, 200, 200))
        for i, arr in enumerate(images[:cols * rows]):
            pic = Image.fromarray(arr[0] if arr.shape[0] == 1 else arr.transpose(1, 2, 0))
            pic = pic.resize((w, h), Image.NEAREST).convert("RGB")
            img.paste(pic, (ox + (i % cols) * (w + 2), pad + 18 + (i // cols) * (h + 2)))
    draw.text((pad, grid_h + pad + 22), title, fill=(160, 160, 160))
    path.parent.mkdir(parents=True, exist_ok=True)
    img.save(path)
    if live:
        print(f"samples: {path}", flush=True)


def density_picture(model: nn.Module, data: np.ndarray, path: Path, title: str,
                    live: bool = False) -> None:
    """Data | model samples | learned density over the first two dimensions."""
    if IMAGES:
        image_picture(model, data, path, title, live)
        return
    from PIL import Image, ImageDraw

    size, pad = 240, 10
    lo = np.percentile(data[:, :2], 0.5, axis=0)
    hi = np.percentile(data[:, :2], 99.5, axis=0)
    span = np.maximum(hi - lo, 1e-6)
    lo, hi = lo - 0.15 * span, hi + 0.15 * span
    img = Image.new("RGB", (3 * size + 4 * pad, size + 2 * pad + 36), (24, 26, 30))
    draw = ImageDraw.Draw(img)

    def to_px(points: np.ndarray, ox: int) -> np.ndarray:
        u = (points[:, :2] - lo) / (hi - lo)
        return np.stack([ox + u[:, 0] * size, pad + 18 + (1 - u[:, 1]) * size], 1)

    model.eval()
    drawn = sample(model, min(2000, max(len(data), 500)), seed=SEED)
    for k, (points, colour) in enumerate(((data[:2000], (90, 150, 240)),
                                          (drawn, (240, 120, 80)))):
        ox = pad + k * (size + pad)
        draw.rectangle([ox, pad + 18, ox + size, pad + 18 + size], outline=(70, 70, 70))
        for px, py in to_px(points, ox):
            if ox <= px <= ox + size and pad + 18 <= py <= pad + 18 + size:
                draw.rectangle([px, py, px + 1, py + 1], fill=colour)
    if INPUT_DIM == 2:
        g = 120
        gx, gy = np.meshgrid(np.linspace(lo[0], hi[0], g), np.linspace(hi[1], lo[1], g))
        dens = np.exp(log_density(model, np.stack([gx.ravel(), gy.ravel()], 1)))
        dens = (dens / max(dens.max(), 1e-12)).reshape(g, g)
        heat = (np.stack([dens * 250, dens * 200 + 30 * (1 - dens), 60 + dens * 60], -1)
                .clip(0, 255).astype(np.uint8))
        img.paste(Image.fromarray(heat).resize((size, size)), (pad + 2 * (size + pad), pad + 18))
    for k, label in enumerate(("data", "samples from the flow",
                               "learned density" if INPUT_DIM == 2 else "(density: 2-D only)")):
        draw.text((pad + k * (size + pad), 4), label, fill=(200, 200, 200))
    draw.text((pad, size + pad + 22), title, fill=(160, 160, 160))
    path.parent.mkdir(parents=True, exist_ok=True)
    img.save(path)
    if live:
        print(f"samples: {path}", flush=True)


def pick_device() -> torch.device:
    if DEVICE != "auto":
        return torch.device(DEVICE)
    if torch.cuda.is_available():
        return torch.device("cuda")
    return torch.device("cpu")      # (MPS lacks some ops the splines use)


def report_resources(device: torch.device, step_seconds: float) -> None:
    peak = torch.cuda.max_memory_allocated(device) / 2**20 if device.type == "cuda" else 0.0
    print(f"resources: peak_memory_mb={peak:.1f} step_ms={step_seconds * 1e3:.2f} "
          f"batch_size={BATCH_SIZE} device={device.type}", flush=True)



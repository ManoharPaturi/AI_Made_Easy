_PREDICTOR = None


def load_predictor(folder: str | Path = ".", device: str = "cpu") -> nn.Module:
    global _PREDICTOR
    with open(Path(folder) / INFERENCE_FILE, "rb") as fh:
        STATE.update(pickle.load(fh))
    model = build_model()
    model.load_state_dict(torch.load(Path(folder) / CHECKPOINT, map_location=device))
    _PREDICTOR = model.eval().to(device)
    return _PREDICTOR


def infer(raw: list) -> list[dict]:
    """A point ([values] or {"column": value}) -> {"log_density"};
    {"sample": n, "seed": s} -> {"samples": [[values], ...]}."""
    if _PREDICTOR is None:
        raise RuntimeError("call load_predictor(folder) first")
    results = []
    for item in raw:
        if isinstance(item, dict) and "sample" in item:
            n = max(1, min(int(item["sample"]), 10000))
            drawn = sample(_PREDICTOR, n, int(item.get("seed", 0)))
            results.append({"samples": [[round(float(v), 6) for v in row] for row in drawn]})
            continue
        if isinstance(item, dict):
            point = [float(item[c]) for c in STATE["columns"]]
        else:
            point = [float(v) for v in item]
        if len(point) != INPUT_DIM:
            raise ValueError(f"expected {INPUT_DIM} values ({STATE['columns']}), "
                             f"got {len(point)}")
        results.append({"log_density": float(log_density(_PREDICTOR, np.array([point]))[0])})
    return results



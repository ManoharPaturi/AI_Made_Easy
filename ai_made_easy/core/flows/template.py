def density_2d(kind: str, n: int, noise: float, seed: int) -> np.ndarray:
    """Points from a 2-D toy distribution."""
    rng = np.random.default_rng(seed)
    if kind == "moons":
        t = rng.uniform(0, np.pi, n)
        upper = rng.random(n) < 0.5
        x = np.where(upper[:, None], np.stack([np.cos(t), np.sin(t)], 1),
                     np.stack([1 - np.cos(t), 0.5 - np.sin(t)], 1)) - [0.5, 0.25]
    elif kind == "circles":
        t = rng.uniform(0, 2 * np.pi, n)
        r = np.where(rng.random(n) < 0.5, 2.0, 1.0)
        x = np.stack([r * np.cos(t), r * np.sin(t)], 1)
    elif kind == "eight_gaussians":
        angle = rng.integers(0, 8, n) * np.pi / 4
        x = 2 * np.stack([np.cos(angle), np.sin(angle)], 1) + rng.normal(0, 0.1, (n, 2))
    elif kind == "checkerboard":
        x1 = rng.uniform(-2, 2, n)
        x2 = rng.uniform(0, 1, n) - 2 * rng.integers(0, 2, n) + np.floor(x1) % 2
        x = np.stack([x1, x2], 1)
    elif kind == "spiral":
        t = np.sqrt(rng.random(n)) * 3 * np.pi
        sign = np.where(rng.random(n) < 0.5, 1.0, -1.0)[:, None]
        x = sign * np.stack([-np.cos(t) * t, np.sin(t) * t], 1) / 3
    elif kind == "pinwheel":
        arms, radial, tangential, rate = 5, 0.3, 0.1, 0.25
        labels = rng.integers(0, arms, n)
        feats = rng.normal(0, 1, (n, 2)) * [radial, tangential] + [1.0, 0.0]
        angles = labels * 2 * np.pi / arms + rate * np.exp(feats[:, 0])
        rot = np.stack([np.cos(angles), -np.sin(angles), np.sin(angles), np.cos(angles)], 1)
        x = 2 * np.einsum("ni,nij->nj", feats, rot.reshape(n, 2, 2))
    else:
        raise SystemExit(f"unknown 2-D density {kind!r}")
    return (x + rng.normal(0, noise, x.shape)).astype(np.float32)


def load_points(d: dict) -> tuple[np.ndarray, list[str]]:
    if d["block"] == "data.density_2d":
        return density_2d(d["kind"], int(d["n_samples"]), float(d["noise"]), int(d["seed"])), \
            ["x1", "x2"]
    import pandas as pd

    path = Path(d["path"]).expanduser()
    frame = pd.read_csv(path, sep="\t" if d.get("format") == "tsv" else ",")
    wanted = [c.strip() for c in str(d.get("feature_columns") or "").split(",") if c.strip()]
    columns = wanted or list(frame.select_dtypes("number").columns)
    missing = [c for c in columns if c not in frame.columns]
    if missing:
        raise SystemExit(f"columns {missing} are not in {path.name}")
    values = frame[columns].astype("float32").dropna().to_numpy()
    return values, columns


def split(n: int, val: float, test: float, seed: int) -> dict:
    order = np.random.default_rng(seed).permutation(n)
    n_test, n_val = int(round(n * test)), int(round(n * val))
    return {"test": order[:n_test], "val": order[n_test:n_test + n_val],
            "train": order[n_test + n_val:]}


# ======================================================================== flow
def flow_layers(model: nn.Module) -> list:
    return [m for m in model.modules() if getattr(m, "is_flow", False)]


def log_prob(model: nn.Module, x: torch.Tensor) -> torch.Tensor:
    """log p(x) of standardised data: standard-normal base plus the log-determinants."""
    z = model(x)
    logdet = sum(m.logdet for m in flow_layers(model))
    return -0.5 * (z ** 2).sum(-1) - 0.5 * z.shape[-1] * LOG_2PI + logdet


@torch.no_grad()
def sample(model: nn.Module, n: int, seed: int = 0) -> np.ndarray:
    """Points drawn from the model, in the original units."""
    device = next(model.parameters()).device
    g = torch.Generator(device="cpu").manual_seed(seed)
    z = torch.randn(n, INPUT_DIM, generator=g).to(device)
    for layer in reversed(flow_layers(model)):
        z = layer.inverse(z)
    return z.cpu().numpy() * STATE["std"] + STATE["mean"]


@torch.no_grad()
def log_density(model: nn.Module, points: np.ndarray, batch: int = 4096) -> np.ndarray:
    """log p(x) in the original units (the standardisation's Jacobian included)."""
    model.eval()
    device = next(model.parameters()).device
    xs = (np.asarray(points, dtype=np.float32) - STATE["mean"]) / STATE["std"]
    out = [log_prob(model, torch.from_numpy(xs[i:i + batch]).to(device)).float().cpu().numpy()
           for i in range(0, len(xs), batch)]
    return np.concatenate(out) - float(np.log(STATE["std"]).sum())


def gaussian_nll(train: np.ndarray, test: np.ndarray) -> float:
    """Mean negative log-likelihood of a full-covariance Gaussian fitted to train."""
    mean = train.mean(0)
    cov = np.cov(train, rowvar=False).reshape(train.shape[1], train.shape[1])
    cov += 1e-6 * np.eye(len(cov))
    diff = test - mean
    _sign, logdet = np.linalg.slogdet(cov)
    maha = np.einsum("ni,ij,nj->n", diff, np.linalg.inv(cov), diff)
    return float(np.mean(0.5 * (maha + logdet + train.shape[1] * LOG_2PI)))


# ======================================================================== pictures
def density_picture(model: nn.Module, data: np.ndarray, path: Path, title: str,
                    live: bool = False) -> None:
    """Data | model samples | learned density over the first two dimensions."""
    from PIL import Image, ImageDraw

    size, pad = 240, 10
    lo = np.percentile(data[:, :2], 0.5, axis=0)
    hi = np.percentile(data[:, :2], 99.5, axis=0)
    span = np.maximum(hi - lo, 1e-6)
    lo, hi = lo - 0.15 * span, hi + 0.15 * span
    img = Image.new("RGB", (3 * size + 4 * pad, size + 2 * pad + 36), (24, 26, 30))
    draw = ImageDraw.Draw(img)

    def to_px(points: np.ndarray, ox: int) -> np.ndarray:
        u = (points[:, :2] - lo) / (hi - lo)
        return np.stack([ox + u[:, 0] * size, pad + 18 + (1 - u[:, 1]) * size], 1)

    model.eval()
    drawn = sample(model, min(2000, max(len(data), 500)), seed=SEED)
    for k, (points, colour) in enumerate(((data[:2000], (90, 150, 240)),
                                          (drawn, (240, 120, 80)))):
        ox = pad + k * (size + pad)
        draw.rectangle([ox, pad + 18, ox + size, pad + 18 + size], outline=(70, 70, 70))
        for px, py in to_px(points, ox):
            if ox <= px <= ox + size and pad + 18 <= py <= pad + 18 + size:
                draw.rectangle([px, py, px + 1, py + 1], fill=colour)
    if INPUT_DIM == 2:
        g = 120
        gx, gy = np.meshgrid(np.linspace(lo[0], hi[0], g), np.linspace(hi[1], lo[1], g))
        dens = np.exp(log_density(model, np.stack([gx.ravel(), gy.ravel()], 1)))
        dens = (dens / max(dens.max(), 1e-12)).reshape(g, g)
        heat = (np.stack([dens * 250, dens * 200 + 30 * (1 - dens), 60 + dens * 60], -1)
                .clip(0, 255).astype(np.uint8))
        img.paste(Image.fromarray(heat).resize((size, size)), (pad + 2 * (size + pad), pad + 18))
    for k, label in enumerate(("data", "samples from the flow",
                               "learned density" if INPUT_DIM == 2 else "(density: 2-D only)")):
        draw.text((pad + k * (size + pad), 4), label, fill=(200, 200, 200))
    draw.text((pad, size + pad + 22), title, fill=(160, 160, 160))
    path.parent.mkdir(parents=True, exist_ok=True)
    img.save(path)
    if live:
        print(f"samples: {path}", flush=True)


def pick_device() -> torch.device:
    if DEVICE != "auto":
        return torch.device(DEVICE)
    if torch.cuda.is_available():
        return torch.device("cuda")
    return torch.device("cpu")      # (MPS lacks some ops the splines use)


def report_resources(device: torch.device, step_seconds: float) -> None:
    peak = torch.cuda.max_memory_allocated(device) / 2**20 if device.type == "cuda" else 0.0
    print(f"resources: peak_memory_mb={peak:.1f} step_ms={step_seconds * 1e3:.2f} "
          f"batch_size={BATCH_SIZE} device={device.type}", flush=True)



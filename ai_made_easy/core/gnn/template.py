_PREDICTOR = None


def load_predictor(folder: str | Path = ".", device: str = "cpu") -> nn.Module:
    global _PREDICTOR
    with open(Path(folder) / INFERENCE_FILE, "rb") as fh:
        STATE.update(pickle.load(fh))
    model = make_model()
    model.load_state_dict(torch.load(Path(folder) / CHECKPOINT, map_location=device))
    _PREDICTOR = model.eval().to(device)
    return _PREDICTOR


def _graph_from(item: dict) -> tuple:
    """A request graph: {"x": [[...]], "edges": [[u, v], ...]} (undirected), or the
    training graph when x is missing."""
    if "x" not in item:
        if "x" not in STATE:
            raise ValueError("send a graph: {\"x\": [[features]], \"edges\": [[u, v], ...]}")
        return STATE["x"], STATE["edge_index"]
    x = np.asarray(item["x"], np.float32).reshape(len(item["x"]), -1)
    edges = np.asarray(item.get("edges") or [], np.int64).reshape(-1, 2).T
    return x, _undirected(edges)


def _labels(logits: torch.Tensor) -> list:
    probs = logits.softmax(-1).cpu().numpy()
    classes = STATE["classes"]
    return [{"label": classes[int(p.argmax())], "confidence": round(float(p.max()), 6),
             "probabilities": {c: round(float(v), 6) for c, v in zip(classes, p)}}
            for p in probs]


@torch.no_grad()
def infer(raw: list) -> list:
    """node_classification: a graph {"x", "edges"} -> one prediction per node, or
    {"nodes": [index, ...]} for nodes of the training graph. graph_classification: a graph
    -> its class. link_prediction: {"pairs": [[u, v], ...]} (optionally with "x" and
    "edges") -> edge probabilities."""
    if _PREDICTOR is None:
        raise RuntimeError("call load_predictor(folder) first")
    device = next(_PREDICTOR.parameters()).device
    out = []
    for item in raw:
        item = item if isinstance(item, dict) else {"nodes": [int(item)]}
        x, ei = _graph_from(item)
        xt = torch.from_numpy(x).to(device)
        et = torch.from_numpy(ei).to(device)
        if KIND == "graph_classification":
            out.append(_labels(_PREDICTOR(xt, et))[0])
        elif KIND == "node_classification":
            rows = _labels(_PREDICTOR(xt, et))
            wanted = item.get("nodes")
            out.append({"nodes": [dict(r, node=i) for i, r in enumerate(rows)
                                  if wanted is None or i in set(wanted)]})
        else:
            pairs = torch.as_tensor(np.asarray(item["pairs"], np.int64).reshape(-1, 2).T,
                                    device=device)
            z = _PREDICTOR(xt, et)
            p = torch.sigmoid(_PREDICTOR.score(z, pairs)).cpu().numpy()
            out.append({"pairs": [[int(u), int(v), round(float(s), 6)]
                                  for (u, v), s in zip(pairs.T.tolist(), p)]})
    return out



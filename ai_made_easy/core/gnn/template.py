class LinkModel(nn.Module):
    """The designed network as a node encoder plus the Link Predictor's decoder."""

    def __init__(self) -> None:
        super().__init__()
        self.encoder = build_model()
        self.decoder = None
        if LINK and LINK["decoder"] == "mlp":
            width = OUTPUT_DIM
            self.decoder = nn.Sequential(nn.Linear(width, LINK["hidden"]), nn.ReLU(),
                                         nn.Linear(LINK["hidden"], 1))

    def forward(self, x, edge_index=None, batch=None):
        return self.encoder(x, edge_index, batch)

    def score(self, z: torch.Tensor, pairs: torch.Tensor) -> torch.Tensor:
        h = z[pairs[0]] * z[pairs[1]]
        return h.sum(-1) if self.decoder is None else self.decoder(h).squeeze(-1)



def _log(epoch: int, train_loss: float, val: dict, optimizer, started: float) -> None:
    shown = " ".join(f"val_{k}={v:.4f}" for k, v in val.items())
    print(f"epoch {epoch}/{EPOCHS} train_loss={train_loss:.4f} {shown} "
          f"lr={optimizer.param_groups[0]['lr']:.3g} ({time.time() - started:.2f}s)",
          flush=True)


def train_loop(model, run_epoch, evaluate_val, key: str, larger_is_better: bool, device):
    params, optimizer, scheduler = _optimizer(model)
    best, best_state, bad = -math.inf, None, 0
    for epoch in range(1, EPOCHS + 1):
        started = time.time()
        model.train()
        train_loss = run_epoch(params, optimizer, scheduler)
        if epoch == 1:
            report_resources(device, time.time() - started)
        model.eval()
        with torch.no_grad():
            val = evaluate_val()
        score = val[key] if larger_is_better else -val[key]
        _epoch_end(scheduler, -score)
        _log(epoch, train_loss, val, optimizer, started)
        if score > best or best_state is None:
            best, bad = score, 0
            best_state = {k: v.detach().cpu().clone() for k, v in model.state_dict().items()}
        else:
            bad += 1
            if EARLY_STOP and bad >= EARLY_STOP:
                print(f"early stopping: no improvement for {EARLY_STOP} epochs")
                break
    model.load_state_dict(best_state)
    return model


# ---------------------------------------------------------------- node classification
def node_task(g: dict, device) -> dict:
    x, ei = tensors(g, device)
    y = torch.from_numpy(np.asarray(g["y"], np.int64)).to(device)
    if "masks" in g:
        parts = {k: np.flatnonzero(v) for k, v in g["masks"].items()}
    else:
        parts = split_ids(len(g["x"]), float(DATASET.get("val_fraction", 0.1)),
                          float(DATASET.get("test_fraction", 0.2)), SEED)
    idx = {k: torch.from_numpy(v).to(device) for k, v in parts.items()}
    n_classes = len(g["classes"])
    print(f"nodes: train={len(parts['train'])} val={len(parts['val'])} "
          f"test={len(parts['test'])} classes={n_classes}")
    model = make_model().to(device)
    loss_fn = nn.CrossEntropyLoss()

    def run_epoch(params, optimizer, scheduler):
        out = model(x, ei)
        loss = loss_fn(out[idx["train"]], y[idx["train"]])
        _step(loss, params, optimizer, scheduler)
        return loss.item()

    def scores(part: str) -> dict:
        out = model(x, ei)
        pred = out[idx[part]].argmax(-1).cpu().numpy()
        m = accuracy_f1(pred, y[idx[part]].cpu().numpy(), n_classes)
        m["loss"] = float(loss_fn(out[idx[part]], y[idx[part]]))
        return m

    model = train_loop(model, run_epoch, lambda: scores("val" if len(parts["val"]) else "train"),
                       "accuracy", True, device)
    model.eval()
    with torch.no_grad():
        metrics = scores("test" if len(parts["test"]) else "val")
    STATE.update({"classes": g["classes"], "x": np.asarray(g["x"], np.float32),
                  "edge_index": np.asarray(g["edge_index"], np.int64), "ids": g.get("ids")})
    return model, metrics


# ---------------------------------------------------------------- graph classification
def to_data(g: dict):
    from torch_geometric.data import Data

    return Data(x=torch.from_numpy(np.asarray(g["x"], np.float32)),
                edge_index=torch.from_numpy(np.asarray(g["edge_index"], np.int64)),
                y=torch.tensor([int(g["y"])]))


def graph_task(graphs: list, classes: list, device) -> dict:
    from torch_geometric.loader import DataLoader

    parts = split_ids(len(graphs), float(DATASET.get("val_fraction", 0.1)),
                      float(DATASET.get("test_fraction", 0.2)), SEED)
    sets = {k: [to_data(graphs[i]) for i in v] for k, v in parts.items()}
    print(f"graphs: train={len(sets['train'])} val={len(sets['val'])} "
          f"test={len(sets['test'])} classes={len(classes)}")
    train_loader = DataLoader(sets["train"], batch_size=BATCH_SIZE, shuffle=True)
    model = make_model().to(device)
    loss_fn = nn.CrossEntropyLoss()

    def run_epoch(params, optimizer, scheduler):
        total, count = 0.0, 0
        for batch in train_loader:
            batch = batch.to(device)
            loss = loss_fn(model(batch.x, batch.edge_index, batch.batch), batch.y)
            _step(loss, params, optimizer, scheduler)
            total += loss.item() * batch.num_graphs
            count += batch.num_graphs
        return total / max(count, 1)

    def scores(items: list) -> dict:
        preds, ys, loss = [], [], 0.0
        for batch in DataLoader(items, batch_size=256):
            batch = batch.to(device)
            out = model(batch.x, batch.edge_index, batch.batch)
            loss += float(loss_fn(out, batch.y)) * batch.num_graphs
            preds.append(out.argmax(-1).cpu().numpy())
            ys.append(batch.y.cpu().numpy())
        m = accuracy_f1(np.concatenate(preds), np.concatenate(ys), len(classes))
        m["loss"] = loss / max(len(items), 1)
        return m

    model = train_loop(model, run_epoch, lambda: scores(sets["val"] or sets["train"]),
                       "accuracy", True, device)
    model.eval()
    with torch.no_grad():
        metrics = scores(sets["test"] or sets["val"])
    counts = np.bincount([int(graphs[i]["y"]) for i in parts["train"]], minlength=len(classes))
    metrics["baseline_accuracy"] = float(counts.max() / max(counts.sum(), 1))
    STATE.update({"classes": classes})
    return model, metrics


# ---------------------------------------------------------------- link prediction
def edge_split(edge_index: np.ndarray, n_nodes: int) -> dict:
    """Unique undirected edges split into train / val / test; message passing sees only
    the training edges (both directions)."""
    pairs = edge_index[:, edge_index[0] < edge_index[1]]
    parts = split_ids(pairs.shape[1], float(DATASET.get("val_fraction", 0.1)),
                      float(DATASET.get("test_fraction", 0.2)), SEED)
    out = {k: pairs[:, v] for k, v in parts.items()}
    rng = np.random.default_rng(SEED + 1)
    existing = set(map(tuple, pairs.T.tolist()))
    for k in ("val", "test"):                       # fixed non-edges for evaluation
        neg = []
        while len(neg) < out[k].shape[1]:
            u, v = sorted(rng.integers(0, n_nodes, 2).tolist())
            if u != v and (u, v) not in existing:
                neg.append((u, v))
        out[k + "_neg"] = np.array(neg, np.int64).T.reshape(2, -1)
    out["message"] = _undirected(out["train"])
    return out


def link_task(g: dict, device) -> dict:
    from torch_geometric.utils import negative_sampling

    n = len(g["x"])
    split = edge_split(np.asarray(g["edge_index"], np.int64), n)
    print(f"edges: train={split['train'].shape[1]} val={split['val'].shape[1]} "
          f"test={split['test'].shape[1]} nodes={n}")
    x = torch.from_numpy(np.asarray(g["x"], np.float32)).to(device)
    mp = torch.from_numpy(split["message"]).to(device)
    pos = torch.from_numpy(split["train"]).to(device)
    model = make_model().to(device)
    bce = nn.BCEWithLogitsLoss()
    n_neg = max(1, int(round(pos.shape[1] * LINK["negatives"])))

    def run_epoch(params, optimizer, scheduler):
        z = model(x, mp)
        neg = negative_sampling(mp, num_nodes=n, num_neg_samples=n_neg)
        logits = torch.cat([model.score(z, pos), model.score(z, neg)])
        labels = torch.cat([torch.ones(pos.shape[1]), torch.zeros(neg.shape[1])]).to(device)
        loss = bce(logits, labels)
        _step(loss, params, optimizer, scheduler)
        return loss.item()

    def scores(part: str) -> dict:
        z = model(x, mp)
        p = torch.from_numpy(split[part]).to(device)
        q = torch.from_numpy(split[part + "_neg"]).to(device)
        s = torch.cat([model.score(z, p), model.score(z, q)]).cpu().numpy()
        labels = np.concatenate([np.ones(p.shape[1]), np.zeros(q.shape[1])])
        return {"roc_auc": roc_auc(s, labels), "average_precision": average_precision(s, labels)}

    part = "val" if split["val"].shape[1] else "train"
    if part == "train":
        split["train_neg"] = split.get("val_neg", np.zeros((2, 0), np.int64))
    model = train_loop(model, run_epoch, lambda: scores(part), "roc_auc", True, device)
    model.eval()
    with torch.no_grad():
        metrics = scores("test" if split["test"].shape[1] else part)
    STATE.update({"x": np.asarray(g["x"], np.float32), "edge_index": split["message"],
                  "ids": g.get("ids")})
    return model, metrics



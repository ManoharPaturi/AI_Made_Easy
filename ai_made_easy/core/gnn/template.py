def _dataset(graph: Graph) -> dict:
    node = dataset_of(graph)
    if node is None and graph_kind(graph) == "graph_classification":
        return {"block": "data.synthetic_graphs", "n_graphs": 600, "min_nodes": 12,
                "max_nodes": 24, "feature_dim": 8, "seed": 0, "val_fraction": 0.1,
                "test_fraction": 0.2}
    if node is None:
        return {"block": "data.synthetic_graph", "n_nodes": 600, "communities": 4,
                "p_in": 0.05, "p_out": 0.005, "feature_dim": 16, "feature_signal": 0.5,
                "seed": 0, "val_fraction": 0.1, "test_fraction": 0.2}
    out = {"block": node.type_id, **dict(node.resolved_params())}
    for key in ("nodes_path", "edges_path"):
        raw = out.get(key)
        if raw and not str(raw).startswith("~") and not Path(str(raw)).is_absolute():
            candidate = Path.cwd() / str(raw)
            if candidate.exists():
                out[key] = str(candidate)
    return out


def _comment(d: dict) -> str:
    block = d["block"]
    if block == "data.synthetic_graph":
        return f"{d['n_nodes']} nodes in {d['communities']} communities (generated)"
    if block == "data.synthetic_graphs":
        return f"{d['n_graphs']} generated graphs with a planted motif"
    if block in ("data.planetoid", "data.tudataset"):
        return f"{d['name']} benchmark"
    return f"{d['nodes_path']} + {d['edges_path']}"


def context(graph: Graph, framework: str) -> dict:
    from ai_made_easy.core.training.generate import own_loop_requirements

    if framework != "pytorch":
        raise CodegenError("graph neural networks train with PyTorch Geometric: choose the "
                           "PyTorch framework")
    kind = graph_kind(graph)
    notes: list[str] = []
    dataset = _dataset(graph)
    if dataset_of(graph) is None:
        notes.append("no dataset block: training on generated "
                     + ("motif graphs" if kind == "graph_classification"
                        else "community graph"))
    loss = next((n for n in graph.nodes.values() if n.type_id in cat.LOSS_IDS), None)
    if loss is not None and (kind == "link_prediction"
                             or loss.type_id != "train.loss_cross_entropy"):
        notes.append(f"the {loss.definition().display_name} block is ignored: "
                     + ("link prediction trains with binary cross-entropy on edges"
                        if kind == "link_prediction" else "classification uses cross-entropy"))
    link = None
    decoder = next((n for n in graph.nodes.values() if n.type_id == "graph.link_decoder"), None)
    if decoder is not None:
        p = decoder.resolved_params()
        link = {"decoder": p["decoder"], "hidden": int(p["hidden"]),
                "negatives": float(p["negatives"])}
    chain = graph.model_nodes()
    shapes = graph.infer_shapes()
    _t, trainer = _picked(graph, ("train.trainer",))
    trainer = cat.resolved("train.trainer", trainer)
    _l, loader = _picked(graph, ("prep.dataloader",))
    opt, opt_params = _picked(graph, cat.OPTIMIZER_IDS)
    optimizer = ("torch.optim.Adam(params, lr=0.01, weight_decay=5e-4)" if opt is None else
                 cat.render(opt.type_id, cat.resolved(opt.type_id, opt_params), "pytorch")
                 .replace("model.parameters()", "params"))
    sched, sched_params = _picked(graph, cat.SCHEDULER_IDS)
    model_code = generate(graph, "pytorch")
    name = sanitize_identifier(graph.name)
    extra = ("pandas",) if dataset["block"] == "data.graph_csv" else ()
    return {
        "title": graph.name, "filename": f"{name}_train_pytorch.py", "name": name,
        "kind": kind, "task_label": TASK_LABELS[kind], "notes": notes, "link": link,
        "requirements": own_loop_requirements(model_code, ("torch_geometric", "scipy",
                                                           *extra)),
        "data_comment": _comment(dataset), "dataset": dataset,
        "input_shape": list(shapes[chain[0].instance_id]),
        "output_dim": int(shapes[chain[-1].instance_id][-1]), "trainer": trainer,
        "batch_size": int(loader.get("batch_size") or 0) or int(trainer["batch_size"]),
        "model_code": _strip_main(model_code), "data_code": runtime.DATA_CODE,
        "metrics_code": runtime.METRICS_CODE, "optimizer_expr": optimizer,
        "scheduler_expr": (cat.render(sched.type_id, cat.resolved(sched.type_id, sched_params),
                                      "pytorch") if sched else None),
        "scheduler_step": cat.COMPONENTS[sched.type_id].meta["step"] if sched else None,
    }



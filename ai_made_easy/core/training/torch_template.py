def cross_validate(device: torch.device) -> None:
    """K-fold cross-validation over the training and validation data."""
    arrays = make_arrays()
    x = np.concatenate([arrays["train"][0], arrays["val"][0]])
    y = np.concatenate([arrays["train"][1], arrays["val"][1]])
    rng = np.random.default_rng(KFOLD_SEED)
    fold = np.zeros(len(y), dtype=int)
    if STRATIFIED and y.ndim == 1 and len(np.unique(y)) < len(y) // 2:
        for c in np.unique(y):
            members = rng.permutation(np.flatnonzero(y == c))
            fold[members] = np.arange(len(members)) % K_FOLDS
    else:
        fold[rng.permutation(len(y))] = np.arange(len(y)) % K_FOLDS
    scores = []
    for k in range(K_FOLDS):
        tr, va = fold != k, fold == k
        train_loader = DataLoader(ArrayDataset(x[tr], y[tr]), batch_size=BATCH_SIZE, shuffle=True)
        val_loader = DataLoader(ArrayDataset(x[va], y[va]), batch_size=BATCH_SIZE)
        model, loss_fn = fit({{ spec.class_name }}().to(device), train_loader, val_loader,
                             device, log=False)
        val_loss, metrics = evaluate(model, loss_fn, val_loader, device)
        metrics = {"loss": val_loss, **metrics}
        scores.append(metrics)
        print(f"fold {k + 1}/{K_FOLDS}: " + " ".join(
            f"{m}={v:.4f}" for m, v in metrics.items() if isinstance(v, float)))
    for m in scores[0]:
        if isinstance(scores[0][m], float):
            vals = np.asarray([s[m] for s in scores])
            print(f"cv {m}: {vals.mean():.4f} ± {vals.std(ddof=1):.4f}")

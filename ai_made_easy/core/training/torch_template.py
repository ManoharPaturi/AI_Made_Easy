def save_sample_png(t: torch.Tensor, path: str) -> None:
    from PIL import Image

    a = t.float().cpu().numpy()
    a = ((a - a.min()) / (a.max() - a.min() + 1e-9) * 255).astype("uint8")
    a = a[0] if a.shape[0] == 1 else np.transpose(a, (1, 2, 0))
    Image.fromarray(a).save(path)



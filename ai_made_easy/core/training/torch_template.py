class FocalLoss(nn.Module):
    """Focal cross-entropy (Lin et al., 2017)."""

    def __init__(self, gamma: float, alpha: float, weight: torch.Tensor | None = None) -> None:
        super().__init__()
        self.gamma, self.alpha, self.weight = gamma, alpha, weight

    def forward(self, logits: torch.Tensor, target: torch.Tensor) -> torch.Tensor:
        ce = F.cross_entropy(logits, target, weight=self.weight, reduction="none")
        loss = (1.0 - torch.exp(-ce)) ** self.gamma * ce
        return (self.alpha * loss if self.alpha else loss).mean()

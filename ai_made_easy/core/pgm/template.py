def format_cpd(cpd) -> list[str]:
    """P(variable | parents) as rows of states × parent combinations (4 decimals)."""
    import itertools

    names = cpd.state_names
    variable, parents = cpd.variable, list(cpd.variables[1:])
    values = cpd.get_values()
    combos = list(itertools.product(*[names[p] for p in parents])) or [()]
    labels = [", ".join(f"{p}={s}" for p, s in zip(parents, c)) or "P" for c in combos]
    width = max(8, *(len(x) for x in labels))
    lines = [f"P({variable}{' | ' + ', '.join(parents) if parents else ''})"]
    lines.append(" " * 12 + " ".join(f"{x:>{width}}" for x in labels))
    for i, state in enumerate(names[variable]):
        lines.append(f"  {str(state)[:10]:<10}" + " ".join(f"{v:>{width}.4f}" for v in values[i]))
    return lines


def report(model, gaussian_cpds, results: list) -> list:
    lines = []
    if gaussian_cpds is not None:
        lines.append("Linear-Gaussian CPDs:")
        for n, (b0, w, std, parents) in gaussian_cpds.items():
            terms = " + ".join(f"{wi:.4g}·{p}" for wi, p in zip(w, parents))
            lines.append(f"  {n} = {b0:.4g}{' + ' + terms if terms else ''} + N(0, {std:.4g}²)")
    elif DESIGN["kind"] != "markov_network":
        lines.append("Conditional probability tables:")
        for cpd in sorted(model.get_cpds(), key=lambda c: c.variable):
            lines += format_cpd(cpd) + [""]
    lines.append("")
    for r in results:
        evidence = ", ".join(f"{k}={v}" for k, v in r["evidence"].items()) or "no evidence"
        lines.append(f"Query {r.get('name') or ', '.join(r['variables'])} | {evidence}")
        if "map" in r:
            lines.append("  most probable: " + ", ".join(f"{k}={v}" for k, v in r["map"].items()))
        for var, dist in r.get("posteriors", {}).items():
            lines.append(f"  {var}: " + ", ".join(f"{s} {p:.4f}" if isinstance(p, float)
                                                   else f"{s} {p}" for s, p in dist.items()))
    return lines



def design(graph: Graph) -> dict:
    """Everything the script needs, as plain data."""
    variables = network.variables(graph)
    model = _picked(graph, "pgm.model") or {"kind": "bayesian_network", "class_variable": "",
                                            "test_fraction": 0.2}
    hmm = _picked(graph, "pgm.hmm")
    structure = _picked(graph, "pgm.structure_learning")
    params = _picked(graph, "pgm.parameter_learning") or {
        "estimator": "em" if any(v.latent for v in variables.values()) else "mle",
        "prior": "BDeu", "equivalent_sample_size": 5.0, "iterations": 100}
    inference = _picked(graph, "pgm.inference") or {"method": "variable_elimination",
                                                    "samples": 5000}
    queries = []
    for node in graph.nodes.values():
        if node.type_id == "pgm.query":
            p = node.resolved_params()
            queries.append({"name": node.instance_id, "variables": _names(p["variables"]),
                            "evidence": _evidence(p["evidence"]), "kind": p["kind"]})
    out_vars = {}
    for name, var in variables.items():
        try:
            table = network.parse_table(var.table)
        except ValueError as exc:
            raise CodegenError(f"{name}: {exc}") from None
        coefficients = [float(c) for c in _names(var.params.get("coefficients", ""))] \
            if var.kind == "gaussian" else []
        out_vars[name] = {"kind": var.kind, "states": var.states, "parents": var.parents,
                          "table": table, "latent": var.latent, "lagged": var.lagged,
                          "intercept": float(var.params.get("intercept", 0.0)),
                          "coefficients": coefficients,
                          "variance": float(var.params.get("variance", 1.0))}
    return {
        "kind": model["kind"], "class_variable": str(model.get("class_variable") or ""),
        "test_fraction": float(hmm["test_fraction"] if hmm else model["test_fraction"]),
        "variables": out_vars, "edges": [list(e) for e in network.edges(graph)],
        "gaussian": any(v.kind == "gaussian" for v in variables.values()),
        "structure": structure, "parameters": params, "inference": inference,
        "queries": queries,
        "hmm": ({**hmm, "observations": _names(hmm["observations"])} if hmm else None),
    }



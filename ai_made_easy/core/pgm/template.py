def infer(raw: list) -> list[dict]:
    """Networks: evidence {"G": "C"} or {"evidence": {...}, "variables": [...], "kind":
    "marginal" | "map"} -> posteriors (Gaussian: mean / std). HMMs: a sequence of
    observations -> the decoded state of every step."""
    if _PREDICTOR is None:
        raise RuntimeError("call load_predictor(folder) first")
    out = []
    for item in raw:
        if _PREDICTOR["kind"] == "hmm":
            X = np.asarray(item.get("observations", item) if isinstance(item, dict) else item)
            X = X.reshape(len(X), -1)
            if DESIGN["hmm"]["emission"] in ("categorical", "poisson"):
                X = X.astype(int)
            model = _PREDICTOR["model"]
            out.append({"states": model.predict(X).tolist(),
                        "probabilities": np.round(model.predict_proba(X), 6).tolist(),
                        "log_likelihood": float(model.score(X))})
            continue
        item = dict(item)
        evidence = item.pop("evidence", None)
        if evidence is None:
            evidence, item = item, {}
        evidence = {k: v if _PREDICTOR["kind"] == "gaussian" else as_state(v)
                    for k, v in evidence.items()}
        variables = item.get("variables") or [n for n in DESIGN["variables"] if n not in evidence]
        for name, value in evidence.items():
            var = DESIGN["variables"].get(name)
            if var is None:
                raise ValueError(f"unknown variable {name!r}")
            if _PREDICTOR["kind"] != "gaussian" and value not in var["states"]:
                raise ValueError(f"{name} has no state {value!r}; states: {var['states']}")
        if _PREDICTOR["kind"] == "gaussian":
            out.append({"posteriors": gaussian_query(_PREDICTOR["cpds"], variables, evidence)})
        else:
            out.append(answer(_PREDICTOR["model"], variables, evidence,
                              item.get("kind", "marginal")))
    return out



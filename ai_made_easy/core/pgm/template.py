def _comment(dataset: dict | None) -> str:
    if dataset is None:
        return "none: the probability tables come from the design"
    if dataset["block"] == "data.network_sample":
        return f"{dataset['n_rows']} rows sampled from the designed network"
    if dataset["block"] == "data.regime_series":
        return f"{dataset['n_steps']} generated steps with {dataset['n_regimes']} regimes"
    return str(dataset.get("path"))



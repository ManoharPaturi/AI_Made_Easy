def as_state(value) -> str:
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    return str(value)


def prepare(frame):
    """The modelled columns: discrete values as state strings (declared order kept),
    Gaussian columns as floats."""
    out = {}
    for name, var in DESIGN["variables"].items():
        if var["latent"]:
            continue
        if name not in frame.columns:
            raise SystemExit(f"the data has no column '{name}' (columns: {list(frame.columns)})")
        if var["kind"] == "gaussian":
            out[name] = pd.to_numeric(frame[name], errors="coerce")
            continue
        column = frame[name].map(lambda v: None if pd.isna(v) else as_state(v))
        seen = sorted({v for v in column if v is not None})
        if var["states"]:
            unknown = [s for s in seen if s not in var["states"]]
            if unknown:
                raise SystemExit(f"{name} has values {unknown[:5]} that are not among its "
                                 f"states {var['states']}")
        else:
            var["states"] = seen
        out[name] = column
    frame = pd.DataFrame(out)
    dropped = int(frame.isna().any(axis=1).sum())
    if dropped and DESIGN["parameters"]["estimator"] != "em":
        print(f"note: {dropped} row(s) with missing values dropped (use the EM estimator to "
              "keep them)")
        frame = frame.dropna()
    return frame


def split(frame):
    if frame is None or DESIGN["test_fraction"] <= 0 or len(frame) < 10:
        return frame, None
    n_test = int(round(len(frame) * DESIGN["test_fraction"]))
    if DESIGN["kind"] in ("dynamic_bn",) or DESIGN["hmm"]:
        return frame.iloc[:-n_test], frame.iloc[-n_test:]      # keep time order
    order = np.random.default_rng(SEED).permutation(len(frame))
    return frame.iloc[order[n_test:]], frame.iloc[order[:n_test]]


# ======================================================================== structure
def learn_structure(train) -> list:
    cfg = DESIGN["structure"]
    method = cfg["method"]
    score = {"bic": "bic-d", "aic": "aic-d", "bdeu": "bdeu", "k2": "k2", "bds": "bds"}[cfg["score"]]
    if DESIGN["gaussian"]:
        score = {"bic": "bic-g", "aic": "aic-g"}.get(cfg["score"], "bic-g")
    if method == "tree":
        from pgmpy.estimators import TreeSearch

        dag = TreeSearch(train).estimate(show_progress=False)
    else:
        from pgmpy import causal_discovery as cd

        if method == "pc":
            est = cd.PC(return_type="dag", significance_level=cfg["significance"],
                        show_progress=False)
        elif method == "ges":
            est = cd.GES(scoring_method=score, return_type="dag")
        else:
            start = None
            if cfg["start_from_design"] and DESIGN["edges"]:
                from pgmpy.base import DAG

                start = DAG(DESIGN["edges"])
                start.add_nodes_from(train.columns)
            est = cd.HillClimbSearch(scoring_method=score, start_dag=start, return_type="dag",
                                     max_indegree=cfg["max_indegree"] or None,
                                     show_progress=False)
        dag = est.fit(train).causal_graph_
    return sorted([list(e) for e in dag.edges()])


# ======================================================================== models
def estimator():
    from pgmpy import parameter_estimator as pe

    cfg = DESIGN["parameters"]
    names = {n: v["states"] for n, v in DESIGN["variables"].items() if not v["latent"]}
    if cfg["estimator"] == "bayesian":
        return pe.DiscreteBayesianEstimator(state_names=names, prior_type=cfg["prior"],
                                            equivalent_sample_size=cfg["equivalent_sample_size"])
    if cfg["estimator"] == "em":
        latent = {n: len(v["states"]) for n, v in DESIGN["variables"].items() if v["latent"]}
        return pe.DiscreteEM(state_names=names, latent_card=latent or None,
                             max_iter=cfg["iterations"], seed=SEED, show_progress=False)
    return pe.DiscreteMLE(state_names=names)


def tabular(name: str):
    from pgmpy.factors.discrete import TabularCPD

    var = DESIGN["variables"][name]
    parents = var["parents"]
    cards = [len(DESIGN["variables"][p]["states"]) for p in parents]
    names = {name: var["states"], **{p: DESIGN["variables"][p]["states"] for p in parents}}
    return TabularCPD(name, len(var["states"]), var["table"], evidence=parents or None,
                      evidence_card=cards or None, state_names=names)


def rename_latents(model) -> None:
    """EM numbers hidden states 0..k-1: show the designed state names instead."""
    from pgmpy.factors.discrete import TabularCPD

    for name, var in DESIGN["variables"].items():
        if not var["latent"]:
            continue
        for cpd in list(model.get_cpds()):
            if name in cpd.state_names:
                names = dict(cpd.state_names)
                names[name] = var["states"]
                evidence = cpd.variables[1:]
                new = TabularCPD(cpd.variable, cpd.variable_card, cpd.get_values(),
                                 evidence=evidence or None,
                                 evidence_card=[cpd.cardinality[i + 1]
                                                for i in range(len(evidence))] or None,
                                 state_names=names)
                model.remove_cpds(cpd)
                model.add_cpds(new)


def discrete_network(edges: list, train):
    from pgmpy.models import DiscreteBayesianNetwork

    latents = {n for n, v in DESIGN["variables"].items() if v["latent"]}
    model = DiscreteBayesianNetwork([tuple(e) for e in edges], latents=latents)
    model.add_nodes_from(DESIGN["variables"])
    if train is not None:
        model = model.fit(train, estimator=estimator()) or model
        rename_latents(model)
    for name, var in DESIGN["variables"].items():
        if var["table"] is not None:
            if train is not None:
                model.remove_cpds(model.get_cpds(name))
            model.add_cpds(tabular(name))
    model.check_model()
    return model


def naive_bayes(train):
    """Naive Bayes as the equivalent star-shaped Bayesian network (class -> every feature)."""
    target = DESIGN["class_variable"]
    edges = [[target, n] for n in DESIGN["variables"] if n != target]
    DESIGN["edges"] = edges
    for name, var in DESIGN["variables"].items():
        var["parents"] = [target] if name != target else []
        var["table"] = None
    return discrete_network(edges, train)


def markov_network(edges: list, train):
    """Pairwise factors P(u, v) / (P(u) P(v)) with unary marginals: exact for tree-shaped
    networks (the Chow-Liu factorisation), an approximation when the network has loops."""
    from pgmpy.factors.discrete import DiscreteFactor
    from pgmpy.models import DiscreteMarkovNetwork

    if train is None:
        raise SystemExit("a Markov network learns its factors from data: add a dataset")
    model = DiscreteMarkovNetwork([tuple(e) for e in edges])
    model.add_nodes_from(DESIGN["variables"])
    V = DESIGN["variables"]

    def marginal(n):
        counts = train[n].value_counts().reindex(V[n]["states"], fill_value=0).to_numpy() + 1.0
        return counts / counts.sum()

    factors = [DiscreteFactor([n], [len(V[n]["states"])], marginal(n),
                              state_names={n: V[n]["states"]}) for n in V]
    for u, v in edges:
        joint = pd.crosstab(train[u], train[v]).reindex(index=V[u]["states"],
                                                         columns=V[v]["states"],
                                                         fill_value=0).to_numpy() + 1.0
        joint /= joint.sum()
        ratio = joint / np.outer(marginal(u), marginal(v))
        factors.append(DiscreteFactor([u, v], [len(V[u]["states"]), len(V[v]["states"])],
                                      ratio.ravel(), state_names={u: V[u]["states"],
                                                                  v: V[v]["states"]}))
    model.add_factors(*factors)
    model.check_model()
    return model


def markov_log_potential(model, rows) -> np.ndarray:
    """Per-row sum of log factor values (the unnormalised log-probability)."""
    total = np.zeros(len(rows))
    for factor in model.get_factors():
        index = np.zeros(len(rows), int)
        for var, card in zip(factor.variables, factor.cardinality):
            states = factor.state_names[var]
            index = index * card + rows[var].map({s: i for i, s in enumerate(states)}).to_numpy()
        total += np.log(np.clip(factor.values.ravel()[index], 1e-300, None))
    return total


def two_slice(frame):
    """Rows (t-1, t) for a dynamic network: columns 'X[t-1]' and 'X[t]'."""
    prev = frame.iloc[:-1].reset_index(drop=True).add_suffix("[t-1]")
    now = frame.iloc[1:].reset_index(drop=True).add_suffix("[t]")
    return pd.concat([prev, now], axis=1)


def dynamic_network(train):
    """A two-slice network: within-step edges in both slices plus lagged edges."""
    V = DESIGN["variables"]
    edges = [[f"{u}[t-1]", f"{v}[t-1]"] for u, v in DESIGN["edges"]]
    edges += [[f"{u}[t]", f"{v}[t]"] for u, v in DESIGN["edges"]]
    edges += [[f"{p}[t-1]", f"{n}[t]"] for n, v in V.items() for p in v["lagged"]]
    unrolled = {}
    for n, v in V.items():
        for suffix in ("[t-1]", "[t]"):
            unrolled[n + suffix] = {**v, "table": None, "latent": False, "lagged": [],
                                    "parents": sorted(u for u, w in edges if w == n + suffix)}
    DESIGN["variables"] = unrolled
    DESIGN["edges"] = sorted(edges)
    return discrete_network(DESIGN["edges"], two_slice(train) if train is not None else None)


def gaussian_network(edges: list, train) -> dict:
    """name -> (intercept, weights, std, parents) for a linear-Gaussian network."""
    V = DESIGN["variables"]
    cpds = {}
    for name, var in V.items():
        parents = sorted(u for u, v in edges if v == name)
        if train is not None:
            X = np.column_stack([np.ones(len(train))] + [train[p].to_numpy() for p in parents])
            beta, *_ = np.linalg.lstsq(X, train[name].to_numpy(), rcond=None)
            resid = train[name].to_numpy() - X @ beta
            cpds[name] = (float(beta[0]), [float(b) for b in beta[1:]],
                          float(max(resid.std(), 1e-9)), parents)
        else:
            coefs = var["coefficients"] or [0.0] * len(parents)
            cpds[name] = (var["intercept"], coefs, math.sqrt(var["variance"]), parents)
    return cpds


def joint_gaussian(cpds: dict) -> tuple:
    names = list(cpds)
    idx = {n: i for i, n in enumerate(names)}
    k = len(names)
    B, c, D = np.zeros((k, k)), np.zeros(k), np.zeros(k)
    for n, (b0, weights, std, parents) in cpds.items():
        c[idx[n]], D[idx[n]] = b0, std ** 2
        for w, p in zip(weights, parents):
            B[idx[n], idx[p]] = w
    inv = np.linalg.inv(np.eye(k) - B)
    return names, inv @ c, inv @ np.diag(D) @ inv.T


def gaussian_query(cpds: dict, variables: list, evidence: dict) -> dict:
    names, mean, cov = joint_gaussian(cpds)
    obs = [names.index(n) for n in evidence]
    out = {}
    for n in variables:
        i = names.index(n)
        if obs:
            s12 = cov[i, obs]
            s22 = cov[np.ix_(obs, obs)]
            gain = np.linalg.solve(s22, s12)
            diff = np.array([float(evidence[o]) for o in evidence]) - mean[obs]
            m, v = mean[i] + gain @ diff, cov[i, i] - gain @ s12
        else:
            m, v = mean[i], cov[i, i]
        out[n] = {"mean": round(float(m), 6), "std": round(float(math.sqrt(max(v, 0))), 6)}
    return out


# ======================================================================== queries
def predict_class(model, rows, target: str) -> np.ndarray:
    """Most probable class for each row given its other columns (MAP query; repeated
    feature combinations are answered once)."""
    eng = engine(model)
    cache: dict = {}
    out = []
    for record in rows.drop(columns=[target]).to_dict("records"):
        evidence = {k: v for k, v in record.items() if v is not None and not pd.isna(v)}
        key = tuple(sorted(evidence.items()))
        if key not in cache:
            cache[key] = answer(model, [target], evidence, "map")["map"][target]
        out.append(cache[key])
    return np.asarray(out, dtype=object).astype(str)


def engine(model):
    method = DESIGN["inference"]["method"]
    from pgmpy.inference import ApproxInference, BeliefPropagation, VariableElimination

    if DESIGN["kind"] == "markov_network" or method == "belief_propagation":
        return BeliefPropagation(model)
    if method == "sampling":
        return ApproxInference(model)
    return VariableElimination(model)


def answer(model, variables: list, evidence: dict, kind: str) -> dict:
    eng = engine(model)
    approx = type(eng).__name__ == "ApproxInference"
    if kind == "map":
        if approx:
            joint = eng.query(variables, evidence=evidence or None, joint=True,
                              n_samples=DESIGN["inference"]["samples"], seed=SEED,
                              show_progress=False)
            best = np.unravel_index(int(np.argmax(joint.values)), joint.values.shape)
            return {"map": {v: joint.state_names[v][i] for v, i in zip(joint.variables, best)}}
        return {"map": dict(eng.map_query(variables, evidence=evidence or None,
                                          show_progress=False))}
    kwargs = {"n_samples": DESIGN["inference"]["samples"], "seed": SEED} if approx else {}
    result = eng.query(variables, evidence=evidence or None, joint=False,
                       show_progress=False, **kwargs)
    return {"posteriors": {v: {s: round(float(p), 6) for s, p in
                               zip(f.state_names[v], f.values)} for v, f in result.items()}}


def run_queries(model, gaussian_cpds) -> list:
    queries = DESIGN["queries"] or [{"variables": [n for n, v in DESIGN["variables"].items()],
                                     "evidence": {}, "kind": "marginal", "name": "marginals"}]
    results = []
    for q in queries:
        if gaussian_cpds is not None:
            res = {"posteriors": gaussian_query(gaussian_cpds, q["variables"], q["evidence"])}
        else:
            res = answer(model, q["variables"], q["evidence"], q["kind"])
        results.append({**q, **res})
    return results


# ======================================================================== HMM
def hmm_model(seed: int):
    from hmmlearn import hmm

    cfg = DESIGN["hmm"]
    common = {"n_components": cfg["n_states"], "n_iter": cfg["iterations"],
              "random_state": seed}
    if cfg["emission"] == "categorical":
        return hmm.CategoricalHMM(**common)
    if cfg["emission"] == "poisson":
        return hmm.PoissonHMM(**common)
    if cfg["emission"] == "gmm":
        return hmm.GMMHMM(n_mix=cfg["mixtures"], covariance_type=cfg["covariance"], **common)
    return hmm.GaussianHMM(covariance_type=cfg["covariance"], **common)


def hmm_arrays(frame) -> tuple:
    cfg = DESIGN["hmm"]
    cols = cfg["observations"]
    missing = [c for c in cols if c not in frame.columns]
    if missing:
        raise SystemExit(f"observation columns {missing} not found (columns: {list(frame.columns)})")
    X = frame[cols].to_numpy()
    if cfg["emission"] in ("categorical", "poisson"):
        X = X.astype(int)
    lengths = (frame.groupby(cfg["sequence_column"], sort=False).size().tolist()
               if cfg["sequence_column"] else [len(frame)])
    return X, lengths


def run_hmm(frame) -> dict:
    cfg = DESIGN["hmm"]
    train, test = split(frame)
    X, lengths = hmm_arrays(train)
    model, ll = None, -math.inf
    for r in range(cfg.get("restarts", 1)):      # EM finds local optima: keep the best start
        candidate = hmm_model(cfg["seed"] + r)
        candidate.fit(X, lengths)
        score = candidate.score(X, lengths)
        print(f"restart {r + 1}: log-likelihood {score:.2f}")
        if score > ll:
            model, ll = candidate, score
    n = len(X)
    metrics = {"train_log_likelihood": ll / n, "bic": float(model.bic(X, lengths)),
               "converged": float(model.monitor_.converged),
               "iterations": float(len(model.monitor_.history))}
    if test is not None and len(test):
        Xt, lt = hmm_arrays(test)
        metrics["test_log_likelihood"] = model.score(Xt, lt) / len(Xt)
    Xa, la = hmm_arrays(frame)
    states = model.predict(Xa, la)
    if "regime" in frame.columns:
        metrics["state_accuracy"] = best_label_accuracy(frame["regime"].to_numpy(), states,
                                                       cfg["n_states"])
    occupancy = np.bincount(states, minlength=cfg["n_states"]) / len(states)
    lines = ["Transition matrix (row: from, column: to):"]
    lines += ["  " + " ".join(f"{p:6.3f}" for p in row) for row in model.transmat_]
    if hasattr(model, "means_"):
        lines += ["", "State means:"] + [f"  state {i}: {np.round(m, 4).tolist()}  "
                                         f"(share {occupancy[i]:.1%})"
                                         for i, m in enumerate(model.means_)]
    SAMPLES_DIR.mkdir(exist_ok=True)
    (SAMPLES_DIR / "report.txt").write_text("\n".join(lines) + "\n")
    draw_regimes(Xa[:, 0].astype(float)[:800], states[:800],
                 "observed series coloured by decoded state").save(SAMPLES_DIR / "regimes.png")
    with open(MODEL_FILE, "wb") as fh:
        pickle.dump({"kind": "hmm", "model": model, "design": DESIGN}, fh)
    return metrics



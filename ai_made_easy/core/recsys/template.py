_PREDICTOR = None


def load_predictor(folder: str | Path = ".", device: str = "cpu") -> nn.Module:
    global _PREDICTOR
    with open(Path(folder) / INFERENCE_FILE, "rb") as fh:
        STATE.update(pickle.load(fh))
    model = build_model()
    model.load_state_dict(torch.load(Path(folder) / CHECKPOINT, map_location=device))
    _PREDICTOR = model.eval().to(device)
    return _PREDICTOR


@torch.no_grad()
def infer(raw: list) -> list[dict]:
    """{"user": id, "k": 10, "exclude_seen": true} -> the top-k items; {"user": id,
    "items": [ids]} -> their scores. Unknown users get the most popular items."""
    if _PREDICTOR is None:
        raise RuntimeError("call load_predictor(folder) first")
    device = next(_PREDICTOR.parameters()).device
    users, items = STATE["user_index"], STATE["item_ids"]
    rows = Rows({"user_features": STATE["user_features"],
                 "item_features": STATE["item_features"]}, device)
    out = []
    for item in raw:
        item = item if isinstance(item, dict) else {"user": item}
        uid = str(item["user"])
        k = max(1, min(int(item.get("k", TOP_K)), len(items)))
        if uid not in users:
            out.append({"user": uid, "known": False,
                        "items": [{"item": items[i], "score": None}
                                  for i in STATE["popular"][:k]]})
            continue
        u = users[uid]
        if "items" in item:
            lookup = {v: i for i, v in enumerate(items)}
            wanted = [lookup[str(v)] for v in item["items"] if str(v) in lookup]
            scores = _PREDICTOR(rows(torch.full((len(wanted),), u, device=device),
                                     torch.as_tensor(wanted, device=device))).squeeze(-1)
            out.append({"user": uid, "known": True,
                        "items": [{"item": items[i], "score": round(float(s), 6)}
                                  for i, s in zip(wanted, scores.cpu().tolist())]})
            continue
        scores = score_matrix(_PREDICTOR, rows, np.array([u]), len(items), device)[0]
        if item.get("exclude_seen", True):
            scores[list(STATE["seen"][u])] = -np.inf
        top = np.argsort(-scores)[:k]
        out.append({"user": uid, "known": True,
                    "items": [{"item": items[i], "score": round(float(scores[i]), 6)}
                              for i in top if np.isfinite(scores[i])]})
    return out



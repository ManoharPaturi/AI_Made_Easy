            if objective == "mse":
                loss = nn.functional.mse_loss(model(rows(u, i)).squeeze(-1), ratings[b])
            elif objective == "bpr":
                j = torch.randint(0, data["n_items"], (len(b),), device=device)
                diff = model(rows(u, i)).squeeze(-1) - model(rows(u, j)).squeeze(-1)

def pick_device() -> torch.device:
    if DEVICE != "auto":
        return torch.device(DEVICE)
    if torch.cuda.is_available():
        return torch.device("cuda")
    if torch.backends.mps.is_available():
        return torch.device("mps")
    return torch.device("cpu")


def report_resources(device: torch.device, step_seconds: float) -> None:
    peak = torch.cuda.max_memory_allocated(device) / 2**20 if device.type == "cuda" else 0.0
    print(f"resources: peak_memory_mb={peak:.1f} step_ms={step_seconds * 1e3:.2f} "
          f"batch_size={BATCH_SIZE} device={device.type}", flush=True)


# ======================================================================== rows
class Rows:
    """Builds model inputs [user, item, *user features, *item features]."""

    def __init__(self, data: dict, device) -> None:
        self.device = device
        uf, itf = data["user_features"], data["item_features"]
        extra = INPUT_SHAPE[0] - 2
        if extra not in (0, uf.shape[1] + itf.shape[1]):
            raise SystemExit(f"the Input holds {INPUT_SHAPE[0]} values but rows are 2 ids + "
                             f"{uf.shape[1] + itf.shape[1]} features")
        self.uf = torch.from_numpy(uf).to(device) if extra else None
        self.itf = torch.from_numpy(itf).to(device) if extra else None

    def __call__(self, users: torch.Tensor, items: torch.Tensor) -> torch.Tensor:
        parts = [users.float().unsqueeze(1), items.float().unsqueeze(1)]
        if self.uf is not None:
            parts += [self.uf[users], self.itf[items]]
        return torch.cat(parts, dim=1)


@torch.no_grad()
def score_matrix(model, rows: Rows, users: np.ndarray, n_items: int, device) -> np.ndarray:
    model.eval()
    items = torch.arange(n_items, device=device)
    out = np.zeros((len(users), n_items), np.float32)
    per = max(1, 200_000 // n_items)
    for start in range(0, len(users), per):
        chunk = torch.as_tensor(users[start:start + per], device=device)
        u = chunk.repeat_interleave(n_items)
        i = items.repeat(len(chunk))
        out[start:start + len(chunk)] = model(rows(u, i)).reshape(len(chunk), n_items).cpu()
    return out


def evaluate(model, rows, data, seen: list, held: list, users: np.ndarray, device,
             relevant_rating: float | None) -> dict:
    scores = score_matrix(model, rows, users, data["n_items"], device)
    for r, u in enumerate(users):
        scores[r, list(seen[u])] = -np.inf
    return ranking_metrics(scores, [held[u] for u in users], TOP_K)


def item_sets(data: dict, idx: np.ndarray, min_rating: float | None = None) -> list:
    sets = [set() for _ in range(data["n_users"])]
    for k in idx:
        if min_rating is None or data["ratings"] is None or data["ratings"][k] >= min_rating:
            sets[data["users"][k]].add(int(data["items"][k]))
    return sets



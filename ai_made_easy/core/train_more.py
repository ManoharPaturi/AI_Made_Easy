"""Train more: continue a finished network for more epochs (3.8), or a boosted-tree model
for more trees (3.9).

A network's new run starts from the finished run's best weights (its fitted preprocessing
comes from the same data, rebuilt identically) and trains for the epochs asked for, as a
tracked run of its own whose note names the run it continues. The optimizer and any
schedule start afresh: Adam's moments are not saved with the weights.

A boosted model (XGBoost, LightGBM, CatBoost, scikit-learn's gradient boosting) keeps its
trees and adds more, fitted on the same training rows with the same class balancing; the
run's fitted preprocessing is reused as it is.
"""
from __future__ import annotations

import copy
import shutil
from pathlib import Path

from ai_made_easy.core.graph import Graph


class TrainMoreError(ValueError):
    """A run that can't be continued."""


BOOSTED = ("ml.xgb_", "ml.lgbm_", "ml.catboost_", "ml.gradient_boosting_",
           "ml.hist_gradient_boosting_")

_BOOSTED_STAGE = '''r"""Train a boosted model more, generated by AI Made Easy."""
import importlib.util
import json
import sys
import time
from pathlib import Path

import joblib
from sklearn.base import clone
from sklearn.pipeline import Pipeline

SOURCE = Path({source!r})
MORE = {more!r}

spec = importlib.util.spec_from_file_location("boosted_model", Path({script!r}))
module = importlib.util.module_from_spec(spec)
sys.modules["boosted_model"] = module
spec.loader.exec_module(module)

X, y = module.load_data()
X_train, X_test, y_train, y_test, fit_params = module.training_split(X, y)
model = joblib.load(next(SOURCE.glob("*_model.joblib")))
name, old = model.steps[-1]
steps = model.steps[:-1]
if any(not hasattr(step, "transform") for _, step in steps):
    raise SystemExit("this pipeline resamples its training rows: retrain it with more trees "
                     "instead")
features = Pipeline(steps).transform(X_train) if steps else X_train
weights = {{k.split("__", 1)[1]: v for k, v in fit_params.items()}}
kind = type(old).__name__
started = time.time()
if kind.startswith(("XGB", "LGBM", "CatBoost")):
    new = clone(old)
    count = "iterations" if "iterations" in new.get_params() and \\
        new.get_params()["iterations"] is not None else "n_estimators"
    new.set_params(**{{count: MORE}})
    if kind.startswith("XGB"):
        new.fit(features, y_train, xgb_model=old.get_booster(), **weights)
    elif kind.startswith("LGBM"):
        new.fit(features, y_train, init_model=old.booster_, **weights)
    else:
        new.fit(features, y_train, init_model=old, **weights)
elif kind.startswith("HistGradientBoosting"):
    new = old.set_params(warm_start=True, max_iter=old.n_iter_ + MORE)
    new.fit(features, y_train, **weights)
elif kind.startswith("GradientBoosting"):
    new = old.set_params(warm_start=True, n_estimators=old.n_estimators_ + MORE)
    new.fit(features, y_train, **weights)
else:
    raise SystemExit(f"{{kind}} is not a boosted model")
model.steps[-1] = (name, new)
elapsed = time.time() - started
trees = (new.get_booster().num_boosted_rounds() if kind.startswith("XGB") else
         new.booster_.current_iteration() if kind.startswith("LGBM") else
         new.tree_count_ if kind.startswith("CatBoost") else
         new.n_iter_ if kind.startswith("HistGradientBoosting") else new.n_estimators_)
train_metrics = module.evaluate(model, X_train, y_train)
test_metrics = module.evaluate(model, X_test, y_test)
numeric = {{k: v for k, v in test_metrics.items() if isinstance(v, float)}}
print("epoch 1/1 " + " ".join(f"train_{{k}}={{v:.4f}}" for k, v in train_metrics.items()
                              if isinstance(v, float))
      + " " + " ".join(f"{{k}}={{v:.4f}}" for k, v in numeric.items()) + f" ({{elapsed:.1f}}s)")
print("test: " + " ".join(f"{{k}}={{v:.4f}}" for k, v in numeric.items()))
joblib.dump(model, module.MODEL_FILE)
module.save_inference_state(X)
print(f"saved model to {{module.MODEL_FILE}} ({{MORE}} more trees, {{trees}} in all)")
Path("metrics.json").write_text(json.dumps({{**test_metrics, "trees": int(trees),
                                            "train": train_metrics}},
                                           indent=1, default=str), encoding="utf-8")
'''


def boosted(graph: dict) -> bool:
    """Whether a design's model is a boosted-tree model that can grow more trees."""
    return any(n.get("type", "").startswith(BOOSTED) for n in graph.get("nodes", []))


def _boosted_script(workdir: Path, source: Path, trees: int) -> Path:
    found = sorted(source.glob("*_train_sklearn.py"))
    if not found or not any(source.glob("*_model.joblib")):
        raise TrainMoreError(f"{source.name} saved no model to continue")
    text = found[0].read_text(encoding="utf-8")
    if "def training_split(" not in text:
        raise TrainMoreError("this run was trained before 3.9: retrain it, then train more")
    shutil.copy2(found[0], Path(workdir) / found[0].name)
    path = Path(workdir) / "stage_train_more.py"
    path.write_text(_BOOSTED_STAGE.format(source=str(source), more=int(trees),
                                          script=found[0].name), encoding="utf-8")
    return path


def _with_epochs(graph: dict, epochs: int) -> dict:
    graph = copy.deepcopy(graph)
    trainers = [n for n in graph.get("nodes", []) if n.get("type") == "train.trainer"]
    if not trainers:
        raise TrainMoreError("the run's design has no Trainer block")
    for node in trainers:
        node.setdefault("params", {})["epochs"] = int(epochs)
    return graph


def start(mgr, run_id: str, epochs: int, lr_scale: float = 1.0,  # noqa: ANN001
          trees: int | None = None) -> str:
    """Continue a finished run: ``epochs`` more for a network, ``trees`` (or ``epochs``)
    more trees for a boosted model."""
    from ai_made_easy.core.pipelines import stages as S

    record = mgr.history.get(run_id)
    if record.status != "finished":
        raise TrainMoreError(f"run {run_id} is {record.status}: only a finished run continues")
    if record.framework == "sklearn" and boosted(record.graph):
        more = int(trees if trees is not None else epochs)
        if not 1 <= more <= 100_000:
            raise TrainMoreError("more trees must be between 1 and 100000")
        source = mgr.history.path(run_id)
        new_id = mgr.start_stage(Graph.from_dict(record.graph),
                                 lambda wd: _boosted_script(wd, source, more),
                                 framework="sklearn", kind="continue",
                                 project=record.project, tags=["train-more"])
        mgr.history.update(new_id, note=f"Continues {run_id} ({record.name}) with {more} more "
                                        "trees")
        return new_id
    if not 1 <= int(epochs) <= 10_000:
        raise TrainMoreError("epochs must be between 1 and 10000")
    if not 0 < float(lr_scale) <= 10:
        raise TrainMoreError("the learning-rate scale must be above 0 and at most 10")
    source = mgr.history.path(run_id)
    try:
        S.script_of(source)
    except FileNotFoundError as exc:
        raise TrainMoreError("Train more continues PyTorch networks and boosted trees; "
                             "retrain other models instead") from exc
    if not any(source.glob("*_best.pt")):
        raise TrainMoreError(f"run {run_id} saved no weights to continue from")
    graph = Graph.from_dict(_with_epochs(record.graph, epochs))
    params = {"freeze": "none", "unfreeze_after": 0, "lr_scale": float(lr_scale),
              "epochs": int(epochs)}
    new_id = mgr.start_stage(graph, lambda wd: S.finetune(wd, source, params),
                             kind="continue", project=record.project,
                             tags=["train-more"])
    mgr.history.update(new_id, note=f"Continues {run_id} ({record.name}) for {int(epochs)} "
                                    "more epochs")
    return new_id

# ------------------------------------------------------------------ losses / metrics

VISION_LOSSES: dict[str, dict] = {}
VISION_METRICS: dict[str, dict] = {}


def _loss(type_id: str, name: str, params: tuple, desc: str) -> BlockDefinition:
    VISION_LOSSES[type_id] = {}
    return BlockDefinition(
        type_id=type_id, display_name=name, category="Loss", color=family_color("training"),
        params=(*params, P("weight", "float", 1.0, lo=0.0,
                           help="Weight when several losses are combined")),
        description=desc, library="PyTorch",
        meta={"kind": "loss", "task": "semantic_segmentation", "vision": True})


def _metric(type_id: str, name: str, key: str, tasks: tuple, desc: str,
            params: tuple = ()) -> BlockDefinition:
    VISION_METRICS[type_id] = {"key": key, "tasks": tasks}
    return BlockDefinition(
        type_id=type_id, display_name=name, category="Metrics",
        color=family_color("evaluation"), params=params, description=desc, library="PyTorch",
        meta={"kind": "metrics", "key": key, "tasks": list(tasks), "vision": True})


BOX_TASKS = ("detection", "instance_segmentation", "keypoints")


def _loss_metric_blocks() -> list[BlockDefinition]:
    return [
        _loss("vision.loss_dice", "Dice Loss", (P("smooth", "float", 1.0, lo=0.0),),
              "1 − Dice overlap per class: robust to class imbalance in segmentation."),
        _loss("vision.loss_tversky", "Tversky Loss",
              (P("alpha", "float", 0.3, lo=0.0, hi=1.0, help="False-positive weight"),
               P("beta", "float", 0.7, lo=0.0, hi=1.0, help="False-negative weight")),
              "Dice generalisation that trades false positives against false negatives."),
        _loss("vision.loss_lovasz", "Lovász-Softmax Loss", (),
              "Directly optimises the mean IoU (Berman et al., 2018)."),
        _loss("vision.loss_focal_pixel", "Pixel Focal Loss",
              (P("gamma", "float", 2.0, lo=0.0),),
              "Cross-entropy that down-weights easy pixels (rare classes, thin structures)."),
        _metric("eval.map", "mAP@[.5:.95]", "map", BOX_TASKS,
                "COCO mean average precision over IoU 0.50–0.95."),
        _metric("eval.map50", "mAP@.5", "map50", BOX_TASKS,
                "Average precision at IoU 0.50 (Pascal VOC style)."),
        _metric("eval.mask_map", "Mask mAP", "mask_map", ("instance_segmentation",),
                "COCO mAP computed on mask IoU."),
        _metric("eval.pck", "PCK", "pck", ("keypoints",),
                "Percentage of correct keypoints within a fraction of the object size.",
                (P("threshold", "float", 0.2, lo=0.01, hi=1.0,
                   help="Fraction of the box diagonal"),)),
        _metric("eval.miou", "Mean IoU", "miou", ("semantic_segmentation",),
                "Intersection over union averaged over classes."),
        _metric("eval.dice", "Dice Score", "dice", ("semantic_segmentation",),
                "Mean Dice (F1) overlap over classes."),
        _metric("eval.pixel_accuracy", "Pixel Accuracy", "pixel_accuracy",
                ("semantic_segmentation",), "Share of correctly classified pixels."),
    ]


def register_all() -> None:
    reg = get_registry()
    for defn in (*_blocks(), *_dataset_blocks(), *_loss_metric_blocks()):
        reg.register(defn)

VISION_DATA: dict[str, dict] = {}


def _data(type_id: str, name: str, params: tuple, desc: str, *, formats: str,
          checks=None) -> BlockDefinition:
    VISION_DATA[type_id] = {"formats": formats}
    return BlockDefinition(
        type_id=type_id, display_name=name, category="Data", color=family_color("data"),
        params=params, description=desc, library="PyTorch", checks_fn=checks,
        meta={"modality": "image", "vision": True, "annotations": formats})



def to_channels(image: torch.Tensor) -> torch.Tensor:
    if INPUT_SHAPE[0] == 1 and image.shape[0] == 3:
        return image.mean(0, keepdim=True)
    return image


def keypoint_array(rec: dict) -> np.ndarray:
    kps = rec.get("keypoints") or []
    if not kps:
        return np.zeros((len(rec["boxes"]), 0, 3), np.float32)
    return np.stack([np.asarray(k, np.float32) for k in kps])


def sanitize(target: dict) -> dict:
    """Clamp boxes to the image, drop degenerate ones, hide keypoints outside the image."""
    h, w = target["boxes"].canvas_size
    boxes = target["boxes"].as_subclass(torch.Tensor).clone()
    boxes[:, 0::2] = boxes[:, 0::2].clamp(0, w)
    boxes[:, 1::2] = boxes[:, 1::2].clamp(0, h)
    keep = ((boxes[:, 2] - boxes[:, 0]) > 1) & ((boxes[:, 3] - boxes[:, 1]) > 1)
    out = {"boxes": boxes[keep], "labels": target["labels"][keep]}
    if "masks" in target:
        out["masks"] = target["masks"].as_subclass(torch.Tensor)[keep].to(torch.uint8)
    if "keypoints" in target:
        pts = target["keypoints"].as_subclass(torch.Tensor)[keep]
        vis = target["visibility"][keep].clone()
        inside = (pts[..., 0] >= 0) & (pts[..., 0] < w) & (pts[..., 1] >= 0) & (pts[..., 1] < h)
        vis[~inside] = 0
        out["keypoints"] = torch.cat([pts, vis.unsqueeze(-1)], dim=-1)
    return out



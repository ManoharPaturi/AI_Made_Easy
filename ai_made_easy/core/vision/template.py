# ======================================================================== losses
def _valid(target: torch.Tensor) -> torch.Tensor:
    return target != IGNORE_INDEX


def _one_hot(logits: torch.Tensor, target: torch.Tensor):
    valid = _valid(target)
    probs = logits.float().softmax(1) * valid.unsqueeze(1)
    onehot = F.one_hot(target.clamp(0, logits.shape[1] - 1), logits.shape[1])
    onehot = onehot.permute(0, 3, 1, 2).float() * valid.unsqueeze(1)
    return probs, onehot


def dice_loss(logits, target, smooth: float = 1.0):
    probs, onehot = _one_hot(logits, target)
    inter = (probs * onehot).sum((0, 2, 3))
    total = probs.sum((0, 2, 3)) + onehot.sum((0, 2, 3))
    return 1 - ((2 * inter + smooth) / (total + smooth)).mean()


def tversky_loss(logits, target, alpha: float = 0.3, beta: float = 0.7):
    probs, onehot = _one_hot(logits, target)
    tp = (probs * onehot).sum((0, 2, 3))
    fp = (probs * (1 - onehot)).sum((0, 2, 3))
    fn = ((1 - probs) * onehot).sum((0, 2, 3))
    return 1 - ((tp + 1) / (tp + alpha * fp + beta * fn + 1)).mean()


def _lovasz_grad(gt_sorted: torch.Tensor) -> torch.Tensor:
    gts = gt_sorted.sum()
    inter = gts - gt_sorted.cumsum(0)
    union = gts + (1 - gt_sorted).cumsum(0)
    jaccard = 1 - inter / union
    if len(gt_sorted) > 1:
        jaccard[1:] = jaccard[1:] - jaccard[:-1]
    return jaccard


def lovasz_loss(logits, target):
    """Lovász-Softmax (Berman et al., 2018) over the classes present in the batch."""
    probs = logits.float().softmax(1).permute(0, 2, 3, 1).reshape(-1, logits.shape[1])
    labels = target.reshape(-1)
    keep = labels != IGNORE_INDEX
    probs, labels = probs[keep], labels[keep]
    losses = []
    for c in labels.unique():
        fg = (labels == c).float()
        errors = (fg - probs[:, c]).abs()
        order = errors.argsort(descending=True)
        losses.append(torch.dot(errors[order], _lovasz_grad(fg[order])))
    return torch.stack(losses).mean() if losses else logits.sum() * 0


def focal_pixel_loss(logits, target, gamma: float = 2.0):
    ce = F.cross_entropy(logits.float(), target, ignore_index=IGNORE_INDEX, reduction="none")
    pt = torch.exp(-ce)
    valid = _valid(target)
    return (((1 - pt) ** gamma) * ce)[valid].mean()


def cross_entropy(logits, target, label_smoothing: float = 0.0):
    return F.cross_entropy(logits.float(), target, ignore_index=IGNORE_INDEX,
                           label_smoothing=label_smoothing)



def _str_literal(s: str) -> str:
    return repr(str(s))


def _bool_lit(v) -> str:
    return "True" if v else "False"


def _list_literal(csv: str) -> str:
    items = [p.strip() for p in str(csv).split(",") if p.strip()]
    return "[" + ", ".join(repr(i) for i in items) + "]"


def generate_llm_script(graph) -> str:
    spec = collect_llm_spec(graph)
    ctx = {
        "spec": spec,
        "do_sample_lit": _bool_lit(spec.generation.get("do_sample")),
        "trust_rc_lit": _bool_lit(spec.model.get("trust_remote_code")),
        "model_id": _str_literal(spec.model["repo_id"]),
        "tokenizer_id": _str_literal(spec.tokenizer["repo_id"]),
        "prompt_template": _str_literal(spec.prompt.get("template", "{input}")),
        "embedder_id": _str_literal(spec.embedding["repo_id"] if spec.embedding else ""),
        "docs_glob": _str_literal(
            (spec.loader or spec.rag or {}).get("docs_path", "docs/*.txt")),
        "docs_encoding": _str_literal(
            (spec.loader or {}).get("encoding", "utf-8")),
        "chunk_size": (spec.splitter or spec.rag or {}).get("chunk_size", 500),
        "chunk_overlap": (spec.splitter or spec.rag or {}).get("chunk_overlap", 50),
        "chunk_separator": _str_literal(
            (spec.splitter or {}).get("separator", "\n\n")),
        "output_schema": _str_literal(
            spec.parser["schema"] if spec.parser else ""),
        "target_modules": _list_literal(spec.lora["target_modules"] if spec.lora else ""),
    }
    # the RAG template expects {context} in the prompt template
    if spec.workflow == "rag":
        template = spec.prompt.get("template", "{input}")
        if "{context}" not in template:
            template = "Context:\\n{context}\\n\\nQuestion: {input}\\nAnswer:"
            ctx["prompt_template"] = _str_literal(template)
    templates = {
        "generate": GENERATE_TEMPLATE,
        "finetune": FINETUNE_TEMPLATE,
        "rag": RAG_TEMPLATE,
    }
    return _env.from_string(templates[spec.workflow]).render(**ctx)

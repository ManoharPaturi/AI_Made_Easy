    generator.eval()

    question = sys.argv[1] if len(sys.argv) > 1 else input("question > ").strip()
    q_vec = embed([question], embed_tok, embed_enc, device)
    hits = store.query(q_vec, TOP_K)
    context = "\\n\\n".join(h[0] for h in hits)

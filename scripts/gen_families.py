"""Write docs/FAMILIES.md from the registries: every family, its tasks, its blocks and the
design rules that check it (the messages come straight from the rule modules, so the
page cannot drift from the code).

    python scripts/gen_families.py           # rewrite docs/FAMILIES.md
    python scripts/gen_families.py --check   # exit 1 when the file is out of date
"""
from __future__ import annotations

import ast
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "FAMILIES.md"
CORE = ROOT / "ai_made_easy" / "core"

# rule modules checked on top of the generic neural lints, by area
NEURAL_AREAS = ("vision", "tabular", "forecast", "speech", "generative", "bayes", "flows",
                "gnn", "recsys", "rl")
ISSUE_CALLS = {"_issue", "ValidationIssue", "issue", "Issue", "_err", "_warn"}
SEVERITY = {"error": "error", "warning": "warning", "info": "note"}


def _text(node: ast.AST) -> str | None:
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    if isinstance(node, ast.JoinedStr):
        return "".join(v.value if isinstance(v, ast.Constant) else "…" for v in node.values)
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        return (_text(node.left) or "…") + (_text(node.right) or "…")
    return None


def rule_messages(path: Path) -> list[tuple[str, str]]:
    """(severity, message) of every issue a rule module can raise, in source order;
    dynamic parts read "…"."""
    found = []
    for node in ast.walk(ast.parse(path.read_text())):
        if not isinstance(node, ast.Call) or len(node.args) < 2:
            continue
        name = getattr(node.func, "id", getattr(node.func, "attr", ""))
        severity = node.args[0].value if isinstance(node.args[0], ast.Constant) else None
        message = _text(node.args[1])
        if name not in ISSUE_CALLS or severity not in SEVERITY or not message:
            continue
        if sum(w.strip("'(),.:").isalpha() for w in message.split()) < 3:
            continue                                  # e.g. "…: …" passes another rule on
        found.append((node.lineno, severity, " ".join(message.split())))
    seen, out = set(), []
    for _line, severity, message in sorted(found):
        if message not in seen:
            seen.add(message)
            out.append((severity, message))
    return out


def _summary(path: Path) -> str:
    doc = ast.get_docstring(ast.parse(path.read_text())) or ""
    first = doc.split("\n\n")[0].replace("\n", " ")
    return first.split(" (")[0].rstrip(".") + "." if first else ""


def _rules(path: Path, title: str | None = None) -> list[str]:
    rows = rule_messages(path)
    if not rows:
        return []
    out = [f"#### {title}", ""] if title else []
    out += [f"- *{SEVERITY[s]}*: " + m.replace("|", "\\|") for s, m in rows]
    return out + [""]


def render() -> str:
    sys.path.insert(0, str(ROOT))
    import ai_made_easy.core.blocks  # noqa: F401 — registers every block and family
    from ai_made_easy.core.families import all_families, family_of
    from ai_made_easy.core.registry import get_registry
    from ai_made_easy.core.tasks import all_tasks

    blocks = [b for b in get_registry().all() if not b.type_id.startswith("custom.")]
    by_family: dict[str, list] = defaultdict(list)
    for block in blocks:
        by_family[family_of({"nodes": [{"id": "n", "type": block.type_id}]}).id].append(block)
    families = sorted(all_families(), key=lambda f: (f.id != "neural", -len(by_family[f.id])))

    lines = [
        "# Model families",
        "",
        "<!-- generated by scripts/gen_families.py from the registries; do not edit -->",
        "",
        f"AI Made Easy has {len(blocks)} blocks in {len(families)} families. A design's "
        "family follows from its blocks; it decides how the design is validated, which "
        "frameworks train it and what code it exports. Every family runs the generic checks "
        "first (unknown blocks, unconnected ports, cycles, port roles, missing optional "
        "libraries), then the rules listed below. Messages are quoted from the code; \"…\" "
        "stands for the values filled in for your design. Many end in a one-click Quick Fix.",
        "",
        "| Family | Blocks | Trains with | Exports | pip extras | Tasks |",
        "| --- | ---: | --- | --- | --- | --- |",
    ]
    for f in families:
        tasks = ", ".join(t.label for t in all_tasks(f.id)) or "—"
        lines.append(f"| [{f.label}](#{f.label.lower().replace(' ', '-')}) | "
                     f"{len(by_family[f.id])} | {', '.join(f.frameworks) or '—'} | "
                     f"{', '.join(f.targets) or '—'} | {', '.join(f.extras) or '—'} | "
                     f"{tasks} |")
    lines.append("")
    for f in families:
        lines += [f"## {f.label}", "", f"`{f.id}`: {f.description}", ""]
        tasks = all_tasks(f.id)
        if tasks:
            lines += ["**Tasks**", ""]
            lines += [f"- **{t.label}** (`{t.id}`){': ' + t.description if t.description else ''}"
                      for t in tasks]
            lines.append("")
        cats: dict[str, list] = defaultdict(list)
        for block in by_family[f.id]:
            cats[block.category].append(block)
        lines += ["**Blocks**", ""]
        for cat in sorted(cats):
            names = sorted({b.display_name for b in cats[cat]})
            needs = sorted({b.extra for b in cats[cat] if getattr(b, "extra", "")})
            extra = f" *(needs `{'`, `'.join(needs)}`)*" if needs else ""
            lines.append(f"- *{cat}* ({len(cats[cat])}){extra}: {', '.join(names)}")
        lines += ["", "**Design rules**", ""]
        if f.id == "neural":
            lines += _rules(CORE / "lints.py", "Every network")
            for area in NEURAL_AREAS:
                path = CORE / area / "rules.py"
                title = _summary(path).replace("Design rules for ", "").rstrip(".")
                lines += _rules(path, title[:1].upper() + title[1:])
        elif f.id == "classic":
            lines += _rules(CORE / "classic" / "generate.py")
        elif f.validate is not None and f.validate.__module__.endswith(".rules"):
            module = f.validate.__module__.split(".")
            lines += _rules(CORE.joinpath(*module[2:-1], "rules.py"))
        if lines[-1] == "**Design rules**" or lines[-2] == "**Design rules**":
            lines += ["The generic checks and the neural network rules for the layers it "
                      "uses.", ""]
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python scripts/gen_families.py")
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())

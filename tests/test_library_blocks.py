    pytest.importorskip("sklearn")
    from verify_classic import pipeline, run_graph

    from ai_made_easy.core.classic import catalog as ml

    scale = "prep.minmax" if tid in (*ml.NONNEGATIVE_TRANSFORMERS, "ml.skewed_chi2_sampler") \
        else "prep.normalize"
    graph = pipeline(f"tr_{tid.split('.')[-1]}", [
        ("data.sklearn", {"dataset": "wine"}), (scale, {}), (tid, {}),
        ("ml.logistic_regression", {}), ("eval.accuracy", {})])
    assert not [i for i in graph.validate() if i.severity == "error"], graph.validate()
    run_graph(graph, tmp_path)



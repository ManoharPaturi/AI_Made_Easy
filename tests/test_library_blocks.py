VARIANTS = {
    "core.conv_lstm2d": [{"return_sequences": True, "kernel_size": 5}],
    "core.transformer": [{"causal": False, "num_encoder_layers": 1, "num_decoder_layers": 3}],
    "core.embedding_bag": [{"mode": "max"}, {"mode": "sum"}],
    "core.constant_pad2d": [{"padding": 2, "value": -1.5}],
    "core.spectral_norm_conv2d": [{"padding": 0, "stride": 2}],
    "core.channel_shuffle": [{"groups": 4}],
    "core.pairwise_distance": [{"p": 1.0}],
    "core.unflatten": [{"dim": 0, "sizes": "2, 4, 4"}],
}


def _cases():
    return [c for c in block_cases(VARIANTS) if c[0] in LIBRARY_IDS]


def test_there_are_twenty_one_new_layers_each_with_a_harness_case():
    assert len(LIBRARY_IDS) == 21
    assert sorted({c[0] for c in _cases()}) == list(LIBRARY_IDS)


@pytest.mark.parametrize("case", _cases(), ids=lambda c: f"{c[0]}-{c[2]}")
def test_runtime_shapes_and_parameter_counts_match(case):
    pytest.importorskip("torch")
    _type_id, _shape, _params, graph = case
    shapes = graph.infer_shapes()
    assert run_torch(graph) == tuple(shapes["out"])
    node = graph.nodes["blk"]
    defn = node.definition()
    if defn.supports("keras"):
        pytest.importorskip("keras")
        got, want = run_keras(graph)
        assert got == want
    ns: dict = {"__name__": "aime_generated"}
    exec(generate(graph, "pytorch"), ns)  # noqa: S102 — generated by us
    real = sum(p.numel() for p in ns[class_name_for(graph.name)]().parameters())
    ins = [shapes["inp"]] * len(defn.inputs)
    if defn.param_fn is not None:
        assert defn.param_fn(ins, node.resolved_params()) == real
    else:
        assert real == 0


def test_the_full_transformer_masks_the_target_only_when_causal():
    by_causal = {c[2].get("causal", True): c[3] for c in _cases() if c[0] == "core.transformer"}
    assert "generate_square_subsequent_mask" in generate(by_causal[True], "pytorch")
    assert "generate_square_subsequent_mask" not in generate(by_causal[False], "pytorch")


def test_shape_errors_explain_the_fix():
    reg = get_registry()
    with pytest.raises(Exception, match="do not split into"):
        reg.get("core.channel_shuffle").shape_fn([[6, 4, 4]], {"groups": 4})
    with pytest.raises(Exception, match="has 36 elements"):
        reg.get("core.unflatten").shape_fn([[32]], {"dim": 0, "sizes": "6, 6"})
    with pytest.raises(Exception, match="odd"):
        reg.get("core.conv_lstm2d").shape_fn([[4, 3, 8, 8]], {"filters": 4, "kernel_size": 4,
                                                             "return_sequences": False})
    with pytest.raises(Exception, match="same E"):
        reg.get("core.transformer").shape_fn([[8, 16], [8, 12]], {"nhead": 4})
    with pytest.raises(Exception, match="windows"):
        reg.get("core.fold").shape_fn([[36, 30]], {"height": 8, "width": 8, "kernel_size": 3,
                                                   "stride": 1, "padding": 0})


def test_new_layers_are_colour_pure_and_documented():
    reg = get_registry()
    colours: dict = {}
    for tid in LIBRARY_IDS:
        d = reg.get(tid)
        assert d.description and d.library
        colours.setdefault(d.category, set()).add(d.color)
    for category, found in colours.items():
        others = {b.color for b in reg.all() if b.category == category}
        assert found <= others and len(others) == 1, category


# ------------------------------------------------------------------ losses and Muon in Keras

@pytest.mark.parametrize("comp_id", ["train.loss_hinge", "train.loss_squared_hinge",
                                     "train.loss_soft_margin", "train.loss_msle",
                                     "train.loss_mape", "train.muon"])
def test_new_losses_and_muon_train_in_keras(comp_id, tmp_path, monkeypatch):
    keras = pytest.importorskip("keras")
    if comp_id == "train.muon" and not hasattr(keras.optimizers, "Muon"):
        pytest.skip("Keras < 3.10 has no Muon")
    from verify_training import chain

    from ai_made_easy.core.codegen.training_gen import generate_training
    from ai_made_easy.core.training import catalog as cat

    task = cat.COMPONENTS[comp_id].meta.get("task", "multiclass")
    if task == "regression":
        data, k = ("data.synthetic", {"kind": "regression", "n_features": 6,
                                      "n_samples": 120}), 1
    else:
        k = 1 if task == "binary" else 3
        data = ("data.synthetic", {"n_features": 6, "n_classes": 2 if k == 1 else 3,
                                   "n_samples": 120})
    graph = chain(f"k_{comp_id.split('.')[-1]}", "6",
                  [("core.dense", {"units": 8}), ("core.relu", {}), ("core.dense", {"units": k})],
                  [data, (comp_id, {}),
                   ("train.trainer", {"epochs": 1, "batch_size": 32, "device": "cpu"})])
    monkeypatch.chdir(tmp_path)
    monkeypatch.setenv("KERAS_BACKEND", "torch")
    code = generate_training(graph, "keras")
    ns: dict = {"__name__": "aime_training"}
    exec(compile(code, f"<{graph.name}>", "exec"), ns)  # noqa: S102
    ns["main"]()



def _metrics(task: str, keys: list[str]):
    import math

    import numpy as np

    from ai_made_easy.core.training import catalog as cat
    from ai_made_easy.core.training.metrics_code import metrics_code

    ids = {c.meta["key"]: c.type_id for c in cat.METRICS}
    code = metrics_code(task, [(ids[k], {}, k) for k in keys])
    ns = {"np": np, "math": math, "to_scores": lambda o: o}
    exec(code, ns)  # noqa: S102
    return ns["compute_metrics"]


def test_new_classification_metrics_match_scikit_learn():
    np = pytest.importorskip("numpy")
    metrics = pytest.importorskip("sklearn.metrics")
    rng = np.random.default_rng(0)
    scores = rng.dirichlet(np.ones(4), 200)
    y = rng.integers(0, 4, 200)
    got = _metrics("multiclass", ["brier", "jaccard"])(scores, y)
    onehot = np.eye(4)[y]
    assert got["brier"] == pytest.approx(np.mean(np.sum((scores - onehot) ** 2, axis=1)))
    assert got["jaccard"] == pytest.approx(
        metrics.jaccard_score(y, scores.argmax(1), average="macro"))
    p = rng.random(100)
    yb = rng.integers(0, 2, 100)
    got = _metrics("binary", ["brier", "jaccard"])(p[:, None], yb)
    assert got["brier"] == pytest.approx(metrics.brier_score_loss(yb, p))
    assert got["jaccard"] == pytest.approx(metrics.jaccard_score(yb, (p >= 0.5).astype(int)))


def test_new_multilabel_metrics_match_scikit_learn():
    np = pytest.importorskip("numpy")
    metrics = pytest.importorskip("sklearn.metrics")
    rng = np.random.default_rng(1)
    scores, y = rng.random((80, 5)), rng.integers(0, 2, (80, 5))
    got = _metrics("multilabel", ["hamming", "jaccard"])(scores, y)
    pred = (scores >= 0.5).astype(int)
    assert got["hamming"] == pytest.approx(metrics.hamming_loss(y, pred))
    assert got["jaccard"] == pytest.approx(
        metrics.jaccard_score(y, pred, average="samples", zero_division=1.0))


def test_new_regression_metrics_match_scipy_and_scikit_learn():
    np = pytest.importorskip("numpy")
    stats = pytest.importorskip("scipy.stats")
    metrics = pytest.importorskip("sklearn.metrics")
    rng = np.random.default_rng(2)
    y = np.round(rng.random(150) * 5, 1)                  # ties, for Spearman
    pred = y + rng.normal(scale=0.5, size=150)
    got = _metrics("regression", ["pearson", "spearman", "max_error", "msle"])(pred, y)
    assert got["pearson"] == pytest.approx(stats.pearsonr(pred, y).statistic)
    assert got["spearman"] == pytest.approx(stats.spearmanr(pred, y).statistic)
    assert got["max_error"] == pytest.approx(metrics.max_error(y, pred))
    assert got["msle"] == pytest.approx(metrics.mean_squared_log_error(
        y, np.clip(pred, 0, None)))



def test_the_quantile_loss_learns_the_quantile():
    torch = pytest.importorskip("torch")
    from ai_made_easy.core.training import catalog as cat

    loss = eval(cat.render("train.loss_quantile", {"quantile": 0.9}, "pytorch"),  # noqa: S307
                {"torch": torch})
    target = torch.randn(4000)
    guess = torch.zeros(1, requires_grad=True)
    opt = torch.optim.Adam([guess], lr=0.05)
    for _ in range(400):
        opt.zero_grad()
        loss(guess.expand(4000), target).backward()
        opt.step()
    assert float(guess) == pytest.approx(float(target.quantile(0.9)), abs=0.08)


def test_the_tweedie_loss_is_lightgbms():
    torch = pytest.importorskip("torch")
    from ai_made_easy.core.training import catalog as cat

    rho = 1.5
    loss = eval(cat.render("train.loss_tweedie", {"power": rho}, "pytorch"),  # noqa: S307
                {"torch": torch})
    y, f = torch.tensor([0.0, 2.0, 5.0]), torch.tensor([0.1, 0.5, 1.5])
    want = (-y * torch.exp((1 - rho) * f) / (1 - rho) + torch.exp((2 - rho) * f) / (2 - rho))
    assert float(loss(f, y)) == pytest.approx(float(want.mean()))



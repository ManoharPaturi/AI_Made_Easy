@pytest.mark.parametrize("case", _cases(), ids=lambda c: f"{c[0]}-{c[2]}")
def test_runtime_shapes_and_parameter_counts_match(case):
    pytest.importorskip("torch")
    _type_id, _shape, _params, graph = case
    shapes = graph.infer_shapes()
    assert run_torch(graph) == tuple(shapes["out"])
    node = graph.nodes["blk"]
    defn = node.definition()
    assert defn.supports("keras")
    pytest.importorskip("keras")
    got, want = run_keras(graph)
    assert got == want
    ns: dict = {"__name__": "aime_generated"}
    exec(generate(graph, "pytorch"), ns)  # noqa: S102 — generated by us
    real = sum(p.numel() for p in ns[class_name_for(graph.name)]().parameters())
    ins = [shapes["inp"]] * len(defn.inputs)
    if defn.param_fn is not None:
        assert defn.param_fn(ins, node.resolved_params()) == real
    else:
        assert real == 0


def _torch_helper(name: str):
    import torch
    from torch import nn

    from ai_made_easy.core.codegen.helpers import PYTORCH_HELPERS

    ns = {"torch": torch, "nn": nn}
    exec(PYTORCH_HELPERS[name], ns)  # noqa: S102
    return ns[name]


def test_sparsemax_is_a_sparse_probability_vector():
    torch = pytest.importorskip("torch")
    out = _torch_helper("Sparsemax")()(torch.tensor([[2.0, 1.0, -1.0], [0.0, 0.0, 0.0]]))
    assert torch.allclose(out, torch.tensor([[1.0, 0.0, 0.0], [1 / 3, 1 / 3, 1 / 3]]))
    x = torch.randn(50, 7)
    y = _torch_helper("Sparsemax")()(x)
    assert torch.allclose(y.sum(-1), torch.ones(50), atol=1e-5) and (y >= 0).all()
    assert (y == 0).any()



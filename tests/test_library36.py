def test_residual_block_keeps_the_input_when_its_branch_is_zero():
    torch = pytest.importorskip("torch")
    block = _torch_helper("ResidualBlock")(4, 4).eval()
    torch.nn.init.zeros_(block.body[-1].weight)            # the last BN's scale
    x = torch.rand(2, 4, 8, 8)
    assert torch.allclose(block(x), x)                     # relu(0 + x) with x >= 0


def test_snake_is_periodic_around_the_identity():
    torch = pytest.importorskip("torch")
    snake = _torch_helper("Snake")(3)
    x = torch.linspace(-3, 3, 30).reshape(1, 3, 10)
    assert torch.allclose(snake(x), x + torch.sin(x) ** 2)



def _train_helper(name: str):
    import math

    import torch
    from torch import nn

    from ai_made_easy.core.training.catalog import TRAIN_HELPERS

    ns = {"torch": torch, "nn": nn, "math": math}
    exec(TRAIN_HELPERS[name], ns)  # noqa: S102
    return ns[name]


@pytest.mark.parametrize("comp_id", ["train.adabelief", "train.adan", "train.ademamix"])
def test_new_optimizers_fit_a_least_squares_problem(comp_id):
    torch = pytest.importorskip("torch")
    from ai_made_easy.core.training import catalog as cat

    torch.manual_seed(0)
    x = torch.randn(256, 5)
    y = x @ torch.tensor([1.0, -2.0, 0.5, 3.0, 0.0]) + 0.3
    model = torch.nn.Linear(5, 1)
    params = cat.resolved(comp_id, {"lr": 0.05, "warmup_steps": 50})
    expr = cat.render(comp_id, params, "pytorch")
    helper = cat.COMPONENTS[comp_id].meta["torch_helper"]
    optimizer = eval(expr, {"model": model, helper: _train_helper(helper)})  # noqa: S307
    first = None
    for _ in range(300):
        optimizer.zero_grad()
        loss = torch.mean((model(x)[:, 0] - y) ** 2)
        first = first if first is not None else float(loss)
        loss.backward()
        optimizer.step()
    assert float(loss) < 0.02 * first, (first, float(loss))


def test_adabelief_takes_adams_first_step():
    torch = pytest.importorskip("torch")
    w1, w2 = torch.nn.Parameter(torch.ones(3)), torch.nn.Parameter(torch.ones(3))
    a = _train_helper("AdaBelief")([w1], lr=0.1)
    b = torch.optim.Adam([w2], lr=0.1)
    for w, opt in ((w1, a), (w2, b)):
        (w * torch.tensor([1.0, -2.0, 3.0])).sum().backward()
        opt.step()
    # one step: Adam moves by lr * sign(g); AdaBelief's (g - m)^2 = (0.9 g)^2 gives lr / 0.9
    assert torch.allclose(1 - w1, (1 - w2) / 0.9, atol=1e-4)


@pytest.mark.parametrize("comp_id,params", [
    ("train.inverse_sqrt_lr", {"warmup_epochs": 3}),
    ("train.wsd_lr", {"warmup_epochs": 2, "decay_fraction": 0.3, "final_factor": 0.1})])
def test_new_schedules_agree_between_pytorch_and_keras(comp_id, params):
    torch = pytest.importorskip("torch")
    from ai_made_easy.core.training import catalog as cat

    p = cat.resolved(comp_id, params)
    epochs = 10
    opt = torch.optim.SGD([torch.nn.Parameter(torch.zeros(1))], lr=1.0)
    sched = eval(cat.render(comp_id, p, "pytorch"),  # noqa: S307
                 {"torch": torch, "optimizer": opt, "EPOCHS": epochs})
    got = []
    for _ in range(epochs):
        got.append(opt.param_groups[0]["lr"])
        opt.step()
        sched.step()
    keras_fn = eval(cat.render(comp_id, p, "keras"), {"LR0": 1.0, "EPOCHS": epochs})  # noqa: S307
    assert got == pytest.approx([keras_fn(e, None) for e in range(epochs)])
    if comp_id == "train.wsd_lr":
        assert got[0] == 0.5 and got[2:7] == [1.0] * 5 and got[-1] == pytest.approx(0.1)



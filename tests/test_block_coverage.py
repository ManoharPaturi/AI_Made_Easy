@pytest.mark.skipif(not has("statsmodels"), reason="needs statsmodels")
@pytest.mark.parametrize("parts", ["structural", "sarimax"])
def test_time_varying_regression_coefficients(parts, tmp_path):
    import test_ssm as t

    rng = np.random.default_rng(0)
    n = 240
    price = rng.uniform(1, 3, n)
    sales = (50 + 0.1 * np.arange(n) + 3 * np.sin(2 * np.pi * np.arange(n) / 12)
             + np.linspace(-2, -6, n) * price + rng.normal(0, 0.4, n))
    (tmp_path / "sales.csv").write_text("sales,price\n" + "".join(
        f"{s:.4f},{p:.4f}\n" for s, p in zip(sales, price, strict=True)))
    model = ([t.n("t", "ssm.trend", kind="local linear trend"), t.n("s", "ssm.seasonal")]
             if parts == "structural" else
             [t.n("a", "ssm.arima", p=1, d=1, q=0, season=12, seasonal_d=1)])
    maes = {}
    for varying in (False, True):
        data = t.design([*model, t.n("r", "ssm.regression", columns="price",
                                     time_varying=varying)],
                        {"horizon": 24}, {"path": str(tmp_path / "sales.csv"),
                                          "target_columns": "sales"}, "data.timeseries_csv")
        run = tmp_path / str(varying)
        run.mkdir()
        run, script = t._run(data, run)
        metrics = json.loads((run / "metrics.json").read_text())
        maes[varying] = metrics["mae"]
    assert metrics["coef_price_first"] == pytest.approx(-2.0, abs=0.5)
    assert metrics["coef_price_last"] == pytest.approx(-5.6, abs=0.8)
    assert maes[True] < maes[False]
    out = t._infer(run, script, [{"history": sales[:100].tolist(),
                                  "past_covariates": price[:100, None].tolist(),
                                  "future_covariates": [[1.0], [3.0]]}])
    assert out[0]["mean"][0] > out[0]["mean"][1]          # a higher price sells less



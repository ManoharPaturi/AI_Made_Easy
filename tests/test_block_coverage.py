def has(module: str) -> bool:
    return importlib.util.find_spec(module) is not None


def node(nid: str, type_id: str, **params) -> dict:
    return {"id": nid, "type": type_id, "params": params, "position": [0, 0]}


def chain(*nodes: dict, extra: tuple = (), name: str = "case") -> dict:
    edges = [{"from": f"{a['id']}/out", "to": f"{b['id']}/in"}
             for a, b in zip(nodes, nodes[1:], strict=False)]
    return {"name": name, "nodes": [*nodes, *extra], "edges": edges}


def messages(data: dict) -> list[str]:
    return [i.message for i in Graph.from_dict(data).validate()]


def train(data: dict | Graph, workdir: Path) -> tuple[dict, Path]:
    from ai_made_easy.core.codegen import export_training
    from ai_made_easy.core.runner.manager import resolve_framework

    graph = data if isinstance(data, Graph) else Graph.from_dict(data)
    workdir.mkdir(parents=True, exist_ok=True)
    script = export_training(graph, resolve_framework(graph), workdir)
    done = subprocess.run([sys.executable, script.name], cwd=workdir, capture_output=True,
                          text=True, timeout=1200)
    assert done.returncode == 0, done.stdout[-2000:] + done.stderr[-3000:]
    return json.loads((workdir / "metrics.json").read_text()), script


def serve(workdir: Path, script: Path, items: list, *args) -> list:
    (workdir / "items.json").write_text(json.dumps(items))   # too long for a command line
    code = (f"import sys, json; sys.path.insert(0, '.'); import {script.stem} as m; "
            f"m.load_predictor('.', *{args!r}); items = json.load(open('items.json')); "
            f"print('OUT ' + json.dumps(m.infer(items)))")
    done = subprocess.run([sys.executable, "-c", code], cwd=workdir, capture_output=True,
                          text=True, timeout=600)
    assert "OUT " in done.stdout, done.stderr[-3000:]
    return json.loads(done.stdout.split("OUT ", 1)[1])



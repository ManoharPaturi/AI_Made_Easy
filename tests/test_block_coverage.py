def _varying_slopes(tmp_path: Path, draws: int = 300) -> dict:
    import pandas as pd

    rng = np.random.default_rng(0)
    cov = np.array([[1.0, -0.35], [-0.35, 0.25]])
    u = rng.multivariate_normal([0, 0], cov, 20)
    rows = [{"school": f"s{g}", "x": x, "y": 2 + u[g, 0] + (1 + u[g, 1]) * x
             + rng.normal(0, 0.3)} for g in range(20) for x in rng.normal(size=30)]
    pd.DataFrame(rows).to_csv(tmp_path / "data.csv", index=False)
    edge = lambda a, b, port: {"from": f"{a}/out", "to": f"{b}/{port}"}  # noqa: E731
    return {"name": "varying_slopes", "nodes": [
        node("data", "data.csv", path=str(tmp_path / "data.csv"), format="csv"),
        node("chol", "ppl.lkj_cholesky", name="chol", size=2, eta=2.0, sd=1.0),
        node("ab", "ppl.mv_normal", name="ab", size=2, group="school"),
        node("a", "ppl.normal", name="mu_a", mu=0.0, sigma=5.0),
        node("b", "ppl.normal", name="mu_b", mu=0.0, sigma=5.0),
        node("mu", "ppl.deterministic", name="mu", expression="mu_a + ab[0] + (mu_b + ab[1]) * x"),
        node("sigma", "ppl.half_normal", name="sigma", sigma=1.0),
        node("y", "ppl.normal", name="y", observed="y"),
        node("sampler", "ppl.sampler", draws=draws, tune=draws, chains=2)],
        "edges": [edge("chol", "ab", "chol"), edge("ab", "mu", "inputs"),
                  edge("a", "mu", "inputs"), edge("b", "mu", "inputs"),
                  edge("mu", "y", "mu"), edge("sigma", "y", "sigma")]}



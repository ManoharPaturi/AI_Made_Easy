def _train(graph, tmp_path) -> dict:
    from ai_made_easy.core.runner.manager import RunManager
    from ai_made_easy.core.runs.history import RunHistory

    mgr = RunManager(RunHistory(tmp_path / "runs"))
    run_id = mgr.start(graph)

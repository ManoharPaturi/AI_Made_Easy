def test_adopt_skips_its_first_step_then_fits_least_squares():
    torch = pytest.importorskip("torch")
    torch.manual_seed(0)
    x = torch.randn(200, 5)
    y = x @ torch.tensor([1.0, -2.0, 0.5, 3.0, 0.0]) + 0.01 * torch.randn(200)
    w = torch.zeros(5, requires_grad=True)
    opt = _adopt([w], lr=0.05)
    for i in range(400):
        opt.zero_grad()
        loss = ((x @ w - y) ** 2).mean()
        loss.backward()
        opt.step()
        if i == 0:      # the first step only records g^2
            assert torch.equal(w.detach(), torch.zeros(5))
    assert float(loss) < 0.05, float(loss)



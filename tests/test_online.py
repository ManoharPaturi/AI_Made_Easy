"""Pretrained weights, for real: every block that downloads weights builds with them and
gives its designed output shape. Opt-in (AIME_ONLINE=1); the nightly CI job runs it with
every extra installed. Offline runs use random weights (scripts/verify_codegen.py)."""
from __future__ import annotations

import os
import sys
from pathlib import Path

import pytest

if os.environ.get("AIME_ONLINE") != "1":
    pytest.skip("downloads pretrained weights: set AIME_ONLINE=1", allow_module_level=True)

torch = pytest.importorskip("torch")
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

from verify_codegen import (  # noqa: E402
    CONTEXTS,
    DEFAULT_OVERRIDES,
    _graph_for,
    _sample,
    block_cases,
)

from ai_made_easy.core.codegen import class_name_for, generate  # noqa: E402
from ai_made_easy.core.registry import get_registry  # noqa: E402

PRETRAINED = sorted(t for t, o in DEFAULT_OVERRIDES.items() if o == {"weights": "none"})


def _build(graph, seed: int):  # noqa: ANN001, ANN202
    ns: dict = {"__name__": "aime_generated"}
    exec(compile(generate(graph, "pytorch"), f"<{graph.name}>", "exec"), ns)
    torch.manual_seed(seed)
    return ns[class_name_for(graph.name)]().eval()


@pytest.mark.parametrize("type_id", PRETRAINED)
def test_pretrained_block_downloads_and_runs(type_id):
    defn = get_registry().get(type_id)
    case = next((c for c in block_cases() if c[0] == type_id), None)
    if case is None:
        pytest.skip(f"{type_id}: its extra is not installed")
    _type, shape, params, _offline = case
    spec = next(p for p in defn.params if p.name == "weights")
    # the default, or the first real checkpoint when the default is random weights
    weights = spec.default if spec.default != "none" else \
        next(o for o in spec.options if o != "none")
    graph = _graph_for(type_id, shape, {**params, "weights": weights},
                       CONTEXTS.get(type_id))
    errors = [i.message for i in graph.validate() if i.severity == "error"]
    assert not errors, errors
    a, b = _build(graph, 0), _build(graph, 1)
    # pretrained weights do not depend on the seed; random initialisation would
    first = next(n for n, p in a.named_parameters() if p.dim() > 1)
    assert torch.equal(dict(a.named_parameters())[first], dict(b.named_parameters())[first])
    shapes = graph.infer_shapes()
    x = _sample(shapes["inp"], graph.nodes["inp"].params.get("dtype") == "int64")  # token ids
    with torch.no_grad():
        out = a(x)
    assert tuple(out.shape[1:]) == tuple(shapes["out"])


# ---------------------------------------------------------------- pretrained recipes

@pytest.mark.parametrize("recipe, knobs, fixture", [
    ("text_encoder_finetune", {"model": "sentence-transformers/all-MiniLM-L6-v2",
                               "max_length": 64, "epochs": 2}, "_reviews"),
    ("audio_encoder_finetune", {"epochs": 2}, "_clips"),
    ("timm_finetune", {"image_size": 96, "epochs": 2}, "_photos"),
])
def test_pretrained_recipe_fine_tunes_real_weights(recipe, knobs, fixture, tmp_path):
    """One real fine-tune per modality: the checkpoint downloads, trains and evaluates."""
    import test_pretrained_recipes as fixtures

    from ai_made_easy.core import recipes, zoo

    rid = recipes.get_recipe(recipe)
    missing = rid.missing()
    if missing:
        pytest.skip(f"{recipe}: needs {missing}")
    data = getattr(fixtures, fixture)(tmp_path / ("reviews.csv" if fixture == "_reviews"
                                                  else "data"))
    graph = recipes.build(rid, "binary", recipes.detect(data), knobs=knobs)
    assert zoo.downloads(graph), "the recipe should download a pretrained checkpoint"
    for node in graph.nodes.values():
        if node.type_id == "train.trainer":
            node.params["batch_size"] = 4
    metrics = fixtures._train(graph, tmp_path / "run")
    assert metrics["accuracy"] >= 0.5


# ---------------------------------------------------------------- generative metrics

def test_inception_score_and_fid_with_real_inception_weights():
    """Inception-v3 downloads; distinct shapes score above one and identical sets match."""
    pytest.importorskip("torchvision")
    import numpy as np

    from ai_made_easy.core import api
    from ai_made_easy.core.generative.image_template import render
    from ai_made_easy.core.graph import Graph

    data = api.read_sample("shapes_gan.json")
    data["nodes"].append({"id": "is", "type": "eval.inception_score",
                          "params": {"splits": 2}, "position": [0, 0]})
    ns: dict = {"__name__": "online"}
    exec(render(Graph.from_dict(data), None, "pytorch"), ns)  # noqa: S102 — generated by us
    images, _labels, _names = ns["synthetic_images"](64, 32, 3, "shapes", 0)
    features, probs = ns["inception_outputs"](images)
    assert features.shape == (64, 2048) and np.allclose(probs.sum(1), 1, atol=1e-4)
    scores = ns["image_scores"](images, images, {"inception_score": "inception",
                                                 "fid": "inception"})
    assert scores["inception_score"] > 1.0 and scores["fid"] < 1.0

def test_attention_recorder_matches_pytorch_attention(tmp_path):
    torch = pytest.importorskip("torch")
    import torch.nn.functional as F

    graph = _vit(tmp_path, [("eval.attention_maps", {})])
    ns: dict = {"__name__": "aime_training"}
    exec(compile(generate_training(graph, "pytorch"), "<vit>", "exec"), ns)  # noqa: S102
    torch.manual_seed(0)
    q, k, v = (torch.randn(2, 4, 6, 8) for _ in range(3))
    kv2 = torch.randn(2, 2, 6, 8)   # grouped-query attention: 2 key / value heads for 4
    bool_mask = torch.rand(6, 6) > 0.3
    bool_mask.fill_diagonal_(True)
    cases = [dict(), dict(is_causal=True), dict(attn_mask=bool_mask),
             dict(attn_mask=torch.randn(6, 6)), dict(scale=0.5)]
    for kw in cases:
        expected = F.scaled_dot_product_attention(q, k, v, **kw)
        with ns["AttentionRecorder"]() as rec:
            got = F.scaled_dot_product_attention(q, k, v, **kw)
        assert torch.allclose(got, expected, atol=1e-5), kw
        assert rec.maps[-1].shape == (2, 4, 6, 6)
        assert torch.allclose(rec.maps[-1].sum(-1), torch.ones(2, 4, 6), atol=1e-5)
    expected = F.scaled_dot_product_attention(q, kv2.repeat_interleave(2, 1),
                                              kv2.repeat_interleave(2, 1))
    with ns["AttentionRecorder"]():
        got = F.scaled_dot_product_attention(q, kv2, kv2, enable_gqa=True)
    assert torch.allclose(got, expected, atol=1e-5)
    # the original is back afterwards, and so is the fused fast path
    assert F.scaled_dot_product_attention.__module__ != "aime_training"


def test_attention_maps_are_skipped_without_attention():
    table = chain("no_attention", "6", [("core.dense", {"units": 2})],
                  [("data.synthetic", {"n_features": 6, "n_classes": 2}),
                   ("train.adam", {}), TRAINER, ("eval.attention_maps", {})])
    spec = collect_spec(table)
    assert spec.attention is None and any("attention or transformer" in w
                                          for w in spec.warnings)
    assert "save_attention_maps" not in generate_training(table, "pytorch")


# ------------------------------------------------------------------ audio saliency

def _audio(root: Path, kind: str, extra=()):
    if kind == "waveform":
        layers = [("core.conv1d", {"out_channels": 4, "kernel_size": 9, "stride": 4}),
                  ("core.relu", {}), ("core.global_avgpool1d", {}), ("core.dense", {"units": 2})]
        shape, feat = "1, 2000", {"kind": "waveform"}
    else:
        layers = [("core.conv2d", {"out_channels": 4, "kernel_size": 3, "padding": 1}),
                  ("core.relu", {}), ("core.global_avgpool2d", {}), ("core.dense", {"units": 2})]
        shape, feat = "1, 32, 13", {"kind": "mel_spectrogram", "n_fft": 256,
                                    "hop_length": 160, "n_mels": 32}
    return chain(f"audio_{kind}", shape, layers, [
        ("data.audio_folder", {"root": str(root), "sample_rate": 8000, "duration": 0.25}),
        ("prep.audio_features", feat), ("eval.accuracy", {}), TRAINER, *extra])


@pytest.mark.parametrize("kind", ["mel_spectrogram", "waveform"])
def test_audio_saliency_is_saved_with_the_run(tmp_path, monkeypatch, kind):
    pytest.importorskip("torch")
    Image = pytest.importorskip("PIL.Image")
    graph = _audio(write_audio(tmp_path), kind, [("eval.audio_saliency", {"n_samples": 2})])
    code, _ = _run(graph, tmp_path, monkeypatch)
    assert "save_audio_saliency(model" in code
    pictures = _pictures(tmp_path, "saliency")
    assert len(pictures) == 2 and "_as_" in pictures[0].stem
    with Image.open(pictures[0]) as im:
        assert im.size[1] >= 128 and im.size[0] >= 2 * im.size[1]



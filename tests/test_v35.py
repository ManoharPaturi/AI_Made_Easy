def test_vision_transformer_attention_is_drawn_over_the_image(tmp_path, monkeypatch):
    pytest.importorskip("torchvision")
    Image = pytest.importorskip("PIL.Image")
    graph = _vit(write_images(tmp_path), [("eval.attention_maps", {"n_samples": 3})])
    code, _ = _run(graph, tmp_path, monkeypatch)
    assert "save_attention_maps(model" in code and "pillow" in code
    pictures = _pictures(tmp_path, "attention")
    assert len(pictures) == 3 and "_as_" in pictures[0].stem
    with Image.open(pictures[0]) as im:
        assert im.size[0] == 2 * im.size[1] and im.size[1] >= 128   # image | map over it
        left, right = im.crop((0, 0, im.size[1], im.size[1])), im.crop(
            (im.size[1], 0, im.size[0], im.size[1]))
        assert left.tobytes() != right.tobytes()



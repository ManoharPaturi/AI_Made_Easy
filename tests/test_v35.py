def _run(graph, tmp_path, monkeypatch) -> tuple[str, dict]:
    monkeypatch.chdir(tmp_path)
    code = generate_training(graph, "pytorch")
    ns: dict = {"__name__": "aime_training"}
    exec(compile(code, f"<{graph.name}>", "exec"), ns)  # noqa: S102 — generated by us
    ns["main"]()
    return code, ns


def _pictures(tmp_path, kind: str) -> list[Path]:
    return sorted((tmp_path / "eval_samples").glob(f"{kind}_*.png"))


# ------------------------------------------------------------------ attention maps

def _vit(root: Path, extra=()):
    return chain("vit_attention", "3, 16, 16", [
        ("vision.patch_embedding", {"patch": 4, "dim": 16, "cls_token": False}),
        ("core.transformer_encoder", {"nhead": 2, "dim_feedforward": 32, "dropout": 0.0,
                                      "activation": "gelu", "norm_first": True}),
        ("core.layer_norm", {}), ("core.reduce", {"op": "mean", "dim": 0}),
        ("core.dense", {"units": 2})], [
        ("data.image_folder", {"root": str(root)}),
        ("prep.resize", {"height": 16, "width": 16}),
        ("train.adam", {"lr": 0.01}), ("eval.accuracy", {}),
        ("train.trainer", {**TRAINER[1], "epochs": 1, "batch_size": 16}), *extra])


